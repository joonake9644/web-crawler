// ---------- git·경로 ----------
// git 출력 한도는 크게 둔다(기본 1MB를 넘는 원장에서 읽기 실패가 "없음"으로 바뀌어 검사가 조용히 꺼지던 경로를 막는다).
const GIT_MAX = 1 << 30;
// 입력은 파이프로 쓰지 않고 임시 파일(권한 600)을 표준입력으로 연결한다. 큰 입력(1MB 넘는 원장)을 파이프로 쓰다가
// node와 git이 서로를 기다리며 멈춘 실측(2026-10-26, 전체 시험 2회 `git hash-object -w --stdin` 10분 이상 정지)이 있다.
function git(args, cwd, input) {
  let tmp = null;
  let fd = null;
  try {
    if (input !== undefined) {
      tmp = path.join(os.tmpdir(), `plan-git-${process.pid}-${crypto.randomBytes(6).toString('hex')}`);
      fs.writeFileSync(tmp, input, { mode: 0o600 });
      fd = fs.openSync(tmp, 'r');
    }
    return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: GIT_MAX, stdio: [fd ?? 'ignore', 'pipe', 'ignore'] }).trimEnd();
  } catch {
    return null;
  } finally {
    if (fd !== null) fs.closeSync(fd);
    if (tmp) fs.rmSync(tmp, { force: true });
  }
}
function gitBuf(args, cwd) {
  try {
    return execFileSync('git', args, { cwd, maxBuffer: GIT_MAX, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return null;
  }
}
// 이력 ref 안의 파일. ref나 파일이 없으면 null, 있는데 읽지 못하면 예외(없음과 읽기 실패를 구분한다).
// 없음은 "커밋이 없음" 또는 "트리에 항목이 없음"일 때만이다. 트리·blob 객체를 읽지 못하는 것(손상·삭제)은 없음이 아니다.
function refFile(P, rel, rev = REF) {
  if (git(['rev-parse', '--verify', '-q', rev], P.top) === null) return null; // ref(또는 그 부모)가 없다
  // ref는 있는데 커밋 객체를 읽지 못하면 손상이다(없음이 아니다).
  if (git(['rev-parse', '--verify', '-q', `${rev}^{commit}`], P.top) === null) throw new Error(`이력 ref 커밋 객체를 읽지 못했다(${rev}). 기록하지 않았다.`);
  const entry = git(['ls-tree', rev, '--', rel], P.top);
  if (entry === null) throw new Error(`이력 ref 트리 읽기 실패(${rev}). 기록하지 않았다.`);
  const m = entry.match(/^\d+ blob ([0-9a-f]+)\t/);
  if (!m) return null;
  const buf = gitBuf(['cat-file', 'blob', m[1]], P.top);
  if (buf === null) throw new Error(`이력 ref 읽기 실패(${rev}:${rel}). 기록하지 않았다.`);
  return buf;
}
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

export function paths(cwd) {
  const top = git(['rev-parse', '--show-toplevel'], cwd);
  if (!top) throw new Error('git 저장소 안에서 실행한다.');
  const common = git(['rev-parse', '--path-format=absolute', '--git-common-dir'], top);
  const gitDir = git(['rev-parse', '--path-format=absolute', '--git-dir'], top);
  const dir = path.join(common, 'plan');
  const linked = path.resolve(common) !== path.resolve(gitDir);
  return {
    top,
    common,
    dir,
    linked,
    mainTop: linked && path.basename(common) === '.git' ? path.dirname(common) : top,
    ledger: path.join(dir, 'ledger.jsonl'),
    inbox: path.join(dir, 'inbox'),
    lock: path.join(dir, '.lock'),
    capsule: path.join(top, CAPSULE_REL),
  };
}

