// 새어 나간 GIT_DIR·GIT_WORK_TREE가 원장을 이 폴더가 아닌 저장소로 돌리면 쓰지 않는다(2026-10-17 docstudio seq 280~286:
// 작업트리 pre-commit 훅의 절대 GIT_DIR이 시험으로 새어 실제 원장에 지시 5건과 DIR-001 상태 변경이 기록됨). 둘 다 없으면 건너뛴다.
export function assertOwnLedger(P) {
  if (!process.env.GIT_DIR && !process.env.GIT_WORK_TREE) return;
  const env = { ...process.env };
  delete env.GIT_DIR;
  delete env.GIT_WORK_TREE;
  let clean = null;
  try {
    clean = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { cwd: P.top, env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trimEnd();
  } catch {}
  const real = (p) => {
    try {
      return fs.realpathSync.native(p);
    } catch {
      return path.resolve(p);
    }
  };
  if (!clean || real(clean) !== real(P.common))
    throw new Error(`GIT_DIR·GIT_WORK_TREE가 이 폴더(${P.top})가 아닌 저장소의 원장(${P.common})을 가리킨다. 기록하지 않았다(시험·훅 환경 누수 의심).`);
}

function withLock(P, fn) {
  assertOwnLedger(P);
  fs.mkdirSync(P.dir, { recursive: true });
  for (let i = 0; i < 50; i++) {
    let fd;
    try {
      fd = fs.openSync(P.lock, 'wx');
    } catch (e) {
      if (e.code !== 'EEXIST') throw e;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
      continue;
    }
    try {
      // 잠금 보유자를 남긴다(남은 잠금을 지워도 되는지 판단할 근거).
      try {
        fs.writeSync(fd, JSON.stringify({ pid: process.pid, host: os.hostname(), ts: new Date().toISOString() }));
      } catch {}
      return fn();
    } finally {
      fs.closeSync(fd);
      fs.rmSync(P.lock, { force: true });
    }
  }
  let holder = '';
  try {
    const h = JSON.parse(fs.readFileSync(P.lock, 'utf8'));
    holder = `, 보유 pid ${h.pid} ${h.host} ${h.ts}`;
  } catch {}
  throw new Error(`원장 잠금 획득 실패(${P.lock}${holder}). 그 pid가 살아 있지 않을 때만(\`ps -p <pid>\`) 이 파일을 지운다. 보유자 정보가 없으면 다른 세션이 끝난 것을 확인한 뒤 지운다.`);
}

// 공유 디렉터리 전체(ledger·revisions·adr)를 refs/plan/ledger 에 커밋으로 남긴다. 작업트리·인덱스는 건드리지 않는다.
function snapshot(P, message) {
  const mk = (entries) => git(['mktree'], P.top, entries.map((e) => `${e.mode} ${e.type} ${e.sha}\t${e.name}`).join('\n') + (entries.length ? '\n' : ''));
  const blob = (f) => git(['hash-object', '-w', f], P.top);
  const entries = [{ mode: '100644', type: 'blob', sha: blob(P.ledger), name: 'ledger.jsonl' }];
  for (const sub of ['adr', 'revisions']) {
    const d = path.join(P.dir, sub);
    if (!fs.existsSync(d)) continue;
    const files = fs.readdirSync(d).filter((f) => fs.statSync(path.join(d, f)).isFile()).sort();
    if (files.length) entries.push({ mode: '040000', type: 'tree', sha: mk(files.map((f) => ({ mode: '100644', type: 'blob', sha: blob(path.join(d, f)), name: f }))), name: sub });
  }
  const tree = mk(entries);
  const parent = git(['rev-parse', '--verify', '-q', REF], P.top);
  const env = { ...process.env };
  if (!git(['config', 'user.name'], P.top)) Object.assign(env, { GIT_AUTHOR_NAME: 'plan-harness', GIT_COMMITTER_NAME: 'plan-harness' });
  if (!git(['config', 'user.email'], P.top)) Object.assign(env, { GIT_AUTHOR_EMAIL: 'plan@localhost', GIT_COMMITTER_EMAIL: 'plan@localhost' });
  const commit = execFileSync('git', ['commit-tree', tree, ...(parent ? ['-p', parent] : []), '-m', message], { cwd: P.top, env, encoding: 'utf8' }).trim();
  execFileSync('git', ['update-ref', REF, commit, ...(parent ? [parent] : [])], { cwd: P.top, stdio: 'ignore' });
}

// 기록의 커밋 지점. 새 원장 내용과 새 스냅샷 파일을 메모리에서 커밋으로 만들고 ref를 먼저 옮긴다(직전 값 확인).
// 파일 쓰기는 그 뒤다. 그래서 ref 이동이 실패하면 아무것도 바뀌지 않고, 실패한 쓰기의 본문이 다음 기록에 섞이지 않는다.
// adr·revisions는 현재 ref 트리에 있는 것 + 이번 파일만 담는다(공통 디렉터리에 남은 고아 파일은 이력에 들어가지 않는다).
function commitSnapshot(P, raw, addBuf, files, message) {
  const ledgerBuf = Buffer.concat([raw, addBuf]);
  const parent = git(['rev-parse', '--verify', '-q', REF], P.top);
  const hashBuf = (buf) => {
    const sha = git(['hash-object', '-w', '--stdin'], P.top, buf);
    if (!/^[0-9a-f]{40,64}$/.test(sha ?? '')) throw new Error('git hash-object 실패(기록하지 않았다).');
    return sha;
  };
  const mk = (entries) => {
    const t = git(['mktree'], P.top, entries.map((e) => `${e.mode} ${e.type} ${e.sha}\t${e.name}`).join('\n') + (entries.length ? '\n' : ''));
    if (!/^[0-9a-f]{40,64}$/.test(t ?? '')) throw new Error('git mktree 실패(기록하지 않았다).');
    return t;
  };
  const over = new Map(files.map((f) => [f.rel, f.buf]));
  const entries = [{ mode: '100644', type: 'blob', sha: hashBuf(ledgerBuf), name: 'ledger.jsonl' }];
  const top = parent ? git(['ls-tree', parent], P.top) : '';
  if (top === null) throw new Error('이력 ref 트리 조회 실패. 기록하지 않았다.');
  for (const sub of ['adr', 'revisions']) {
    const have = new Map();
    if (parent) {
      // 이력 ref가 있으면 바탕은 ref 트리뿐이다(그 하위 트리가 없으면 빈 바탕). 공통 디렉터리의 고아 파일을 흡수하지 않는다.
      if (new RegExp(`^040000 tree [0-9a-f]+\\t${sub}$`, 'm').test(top)) {
        const list = git(['ls-tree', `${parent}:${sub}`], P.top);
        if (list === null) throw new Error(`이력 ref ${sub} 트리 조회 실패. 기록하지 않았다.`);
        for (const line of list.split('\n').filter(Boolean)) {
          const m = line.match(/^(\d+) (\w+) ([0-9a-f]+)\t(.+)$/);
          if (m && m[2] === 'blob') have.set(m[4], m[3]);
        }
      }
    } else {
      // 이력 ref가 아직 없는 옛 설치: 공통 디렉터리의 기존 파일이 첫 스냅샷의 바탕이다.
      const d = path.join(P.dir, sub);
      for (const f of fs.existsSync(d) ? fs.readdirSync(d) : []) if (fs.statSync(path.join(d, f)).isFile()) have.set(f, hashBuf(fs.readFileSync(path.join(d, f))));
    }
    for (const [rel, buf] of over) if (rel.startsWith(`${sub}/`)) have.set(rel.slice(sub.length + 1), hashBuf(buf));
    if (have.size) entries.push({ mode: '040000', type: 'tree', sha: mk([...have.keys()].sort().map((name) => ({ mode: '100644', type: 'blob', sha: have.get(name), name }))), name: sub });
  }
  const tree = mk(entries);
  const env = { ...process.env };
  if (!git(['config', 'user.name'], P.top)) Object.assign(env, { GIT_AUTHOR_NAME: 'plan-harness', GIT_COMMITTER_NAME: 'plan-harness' });
  if (!git(['config', 'user.email'], P.top)) Object.assign(env, { GIT_AUTHOR_EMAIL: 'plan@localhost', GIT_COMMITTER_EMAIL: 'plan@localhost' });
  const commit = execFileSync('git', ['commit-tree', tree, ...(parent ? ['-p', parent] : []), '-m', message], { cwd: P.top, env, encoding: 'utf8' }).trim();
  execFileSync('git', ['update-ref', REF, commit, ...(parent ? [parent] : [])], { cwd: P.top, stdio: 'ignore' });
  // ref가 옮겨진 뒤에 파일을 쓴다. 여기서 실패하면 작업 원장이 ref보다 뒤처지고, 다음 기록이 ref 기준으로 채운 뒤 이어 쓴다.
  for (const f of files) {
    fs.mkdirSync(path.dirname(path.join(P.dir, f.rel)), { recursive: true });
    fs.writeFileSync(path.join(P.dir, f.rel), f.buf);
  }
  fs.appendFileSync(P.ledger, addBuf);
}

// 작업 원장이 확정 지점(이력 ref)보다 뒤처졌으면(기록의 파일 쓰기 실패) ref 기준으로 채운다. 쓰기 명령은 상태를 읽기 전에 부른다.
// 앞서거나 갈라졌으면 손대지 않는다(check가 알리고 appendEvent가 거부한다).
export function healFromRef(P) {
  if (!fs.existsSync(P.ledger)) return false;
  return withLock(P, () => {
    const raw = fs.readFileSync(P.ledger);
    const refLedger = refFile(P, 'ledger.jsonl');
    if (!refLedger || refLedger.length <= raw.length || !refLedger.subarray(0, raw.length).equals(raw)) return false;
    fs.appendFileSync(P.ledger, refLedger.subarray(raw.length));
    return true;
  });
}

// 기본 브랜치(origin/HEAD, 없으면 origin/main·master, main·master)에 커밋된 CLI. 판 전환 판정용.
export function defaultBranchCli(P) {
  const head = git(['symbolic-ref', '--quiet', 'refs/remotes/origin/HEAD'], P.top);
  for (const r of [head, 'refs/remotes/origin/main', 'refs/remotes/origin/master', 'refs/heads/main', 'refs/heads/master'].filter(Boolean)) {
    if (!git(['rev-parse', '--verify', '-q', `${r}^{commit}`], P.top)) continue;
    let blob = git(['rev-parse', '--verify', '-q', `${r}:.plan/bin/plan.mjs`], P.top);
    // 링크(120000)로 커밋된 사본(하네스 원본 저장소)은 링크 대상 파일로 판정한다.
    const mode = (git(['ls-tree', r, '.plan/bin/plan.mjs'], P.top) ?? '').split(' ')[0];
    if (blob && mode === '120000') {
      const target = path.posix.normalize(path.posix.join('.plan/bin', git(['cat-file', '-p', blob], P.top) ?? ''));
      blob = git(['rev-parse', '--verify', '-q', `${r}:${target}`], P.top);
    }
    return { ref: r.replace(/^refs\/(remotes\/|heads\/)/, ''), blob, text: blob ? git(['cat-file', '-p', blob], P.top) : null };
  }
  return { ref: null, blob: null, text: null };
}
// 이번 기록에 쓸 형식. 원장에 이미 WRITE_SCHEMA 이상이 있거나, 기본 브랜치에 schema 3으로 쓰는 옛 판 CLI가 없을 때만 올린다.
// 그래야 기본 브랜치에서 갈라지는 세션 브랜치·`--worktree` 작업트리(옛 판)가 반영 전에 쓰기 차단에 걸리지 않는다.
export function writeSchemaFor(P, events) {
  if (events.some((e) => (e.schema ?? 0) >= WRITE_SCHEMA)) return { schema: WRITE_SCHEMA };
  const d = defaultBranchCli(P);
  if (!d.ref) return { schema: 3, why: '기본 브랜치(origin/HEAD·main·master)를 찾지 못했다' };
  if (!d.text) return { schema: WRITE_SCHEMA };
  const m = d.text.match(/^export const WRITE_SCHEMA = (\d+);/m);
  if (m && Number(m[1]) >= WRITE_SCHEMA) return { schema: WRITE_SCHEMA };
  return { schema: 3, why: `기본 브랜치 ${d.ref}의 CLI(blob ${String(d.blob).slice(0, 7)})가 schema 3으로 쓰는 옛 판이다` };
}

// verify(events)를 주면 잠금 안에서 최신 원장으로 한 번 더 검사한다(조각 WIP 1처럼 동시 기록 경합을 막을 조건).
export function appendEvent(P, event, files = [], verify = null, extra = []) {
  return withLock(P, () => {
    let { events, errors, fromRef, raw } = readLedger(P);
    if (errors.length) throw new Error(errors.join('\n'));
    if (fromRef) throw new Error('작업 원장이 없다(이력 ref만 있음). `plan restore`로 복구한 뒤 기록한다.');
    const newest = Math.max(0, ...events.map((e) => e.schema ?? 0));
    if (newest > MAX_SCHEMA) throw new Error(`이 원장은 더 새 CLI(schema ${newest})가 기록했다. 이 CLI(schema ${MAX_SCHEMA}까지)로는 쓰지 않는다. 전역 \`~/.plan-harness/bin/plan.mjs\`를 쓰거나 하네스 원본 \`install.mjs\`로 이 작업트리 CLI를 갱신한다.`);
    // 확정 지점은 이력 ref다. 작업 원장이 ref보다 뒤처졌으면(직전 기록의 파일 쓰기 실패) ref 기준으로 채운 뒤 이어 쓴다.
    // ref보다 앞서거나 갈라졌으면 쓰지 않는다(CLI 밖 추가를 이력에 흡수하지 않는다).
    const refLedger = refFile(P, 'ledger.jsonl');
    if (refLedger && !raw.equals(refLedger)) {
      if (refLedger.length > raw.length && refLedger.subarray(0, raw.length).equals(raw)) {
        fs.appendFileSync(P.ledger, refLedger.subarray(raw.length));
        ({ events, errors, raw } = readLedger(P));
        if (errors.length) throw new Error(errors.join('\n'));
      } else throw new Error('작업 원장이 이력 ref와 다르다(CLI 밖 추가·삭제·수정). 기록하지 않았다. `plan check`로 확인하고 `plan restore`로 이력본을 복구한 뒤 기록한다.');
    }
    verify?.(events);
    const full ={ schema: writeSchemaFor(P, events).schema, seq: (events.at(-1)?.seq ?? 0) + 1, ts: event.ts ?? new Date().toISOString(), ...event };
    if (full.by === 'user' && full.quote) {
      const candidates = listInbox(P).filter((r) => classifyRecord(r) === 'user' && !syntheticPrompt(r.prompt) && String(r.prompt).includes(String(full.quote ?? '')) && full.quote && (!full.approval_ref || r.id === full.approval_ref));
      if (candidates.length !== 1) throw new Error('승인 원문을 실제 사용자 입력 한 건에 연결해야 한다. `--approval-ref <inbox ID>`로 지정한다. 수동 --text·출처 불명·에이전트 입력은 승인 근거가 아니다.');
      const r = candidates[0];
      full.approval = { ref: r.id, sha256: sha256(r.prompt), origin: r.origin, tool: r.tool, session: r.session };
    }
    if (full.type === 'adr.status') {
      if (full.source === 'migration' && full.status !== 'proposed' && events.some((e) => e.schema >= 3 && e.source !== 'migration')) throw new Error('새 프로토콜에서 결정 등록을 시작한 뒤에는 ADR 이관으로 결정 확정을 우회할 수 없다. 사용자 원문으로 결정을 기록한다.');
      const f = files.find((f) => f.rel === `adr/${full.id}.md`);
      if (f) {
        const previous = fold(events).adrs.get(full.id);
        if (previous && ['accepted', 'rejected', 'superseded'].includes(previous.status)) {
          const old = readSnap(P, previous.snapshot);
          if (old && !sameDecision(previous, old, f.buf)) throw new Error(`${full.id} 확정 ADR 본문은 다시 승인해서 덮어쓸 수 없다. 새 ADR로 대체한다.`);
          if (full.status === 'proposed') throw new Error(`${full.id} 확정 ADR을 proposed로 되돌릴 수 없다. 새 ADR을 제안한다.`);
        }
        full.snapshot = `adr/${full.id}-${full.seq}.md`;
        full.sha256 = sha256(f.buf);
        files = [...files, { rel: full.snapshot, buf: f.buf }];
      }
    }
    const additions = [full];
    if (full.approval) additions.push({ schema: full.schema, seq: full.seq + 1, ts: full.ts, type: 'inbox.triage', refs: withDups(P, [full.approval.ref]), as: `quote:#${full.seq}` });
    if (extra.length) {
      // 같은 기록 안에서 근거 입력을 두 번 쓰지 않는다(1회 사용). 쓸 때 통과하고 읽을 때 ERROR가 되는 원장을 만들지 않는다.
      const seen = new Set(full.approval ? withDups(P, [full.approval.ref]) : []);
      const triaged = fold(events).triaged;
      for (const x of extra)
        for (const r of x.refs ?? [x.ref]) {
          if (seen.has(r) || triaged.has(r)) throw new Error(`근거 입력 ${r}를 한 기록에서 두 번 쓰거나 이미 분류된 입력을 다시 쓸 수 없다(1회 사용). 승인마다 사용자 입력을 따로 받는다.`);
          seen.add(r);
        }
    }
    for (const x of extra) additions.push({ schema: full.schema, seq: additions.at(-1).seq + 1, ts: full.ts, ...x }); // 같은 기록에 묶을 분류(지연 승인 등)
    const problems = validateEvents([...events, ...additions]);
    if (problems.length) throw new Error(problems.join('\n'));
    commitSnapshot(P, raw, Buffer.from(additions.map((e) => JSON.stringify(e)).join('\n') + '\n'), files, `plan #${full.seq} ${full.type} ${full.id ?? full.rev ?? ''}`.trim());
    return full;
  });
}

// ---------- 접기(fold)와 전이 규칙 ----------
export function fold(events) {
  const s = { directives: new Map(), order: [], plans: [], plan: null, adrs: new Map(), triaged: new Set(), lastSeq: 0, planSeq: 0 };
  for (const e of events) {
    s.lastSeq = e.seq;
    if (e.type !== 'inbox.triage') s.planSeq = e.seq; // 입력 분류는 캡슐을 바꾸지 않는다.
    if (e.type === 'directive.add') {
      s.directives.set(e.id, { id: e.id, text: e.text, source: e.source, status: 'OPEN', ts: e.ts, seq: e.seq, amendments: [] });
      s.order.push(e.id);
    } else if (e.type === 'directive.amend') {
      s.directives.get(e.id)?.amendments.push({ text: e.text, source: e.source, seq: e.seq, by: e.by, backed: !!(e.by === 'user' && e.approval?.ref) });
    } else if (e.type === 'directive.status') {
      const d = s.directives.get(e.id);
      if (!d) continue;
      Object.assign(d, {
        status: e.status,
        blocker: e.status === 'BLOCKED' ? e.blocker : undefined,
        unblock: e.status === 'BLOCKED' ? e.unblock : undefined,
        evidence: e.evidence ?? d.evidence,
        work: e.work ?? d.work,
        next: e.next ?? d.next,
      });
    } else if (e.type === 'order.set') {
      s.order = [...e.order, ...s.order.filter((id) => !e.order.includes(id))];
    } else if (e.type === 'plan.revise') {
      s.plans.push(e);
      s.plan = e;
    } else if (e.type === 'plan.retrigger') {
      const i = s.plans.findIndex((p) => p.rev === e.rev);
      if (i >= 0) {
        const corrected = { ...s.plans[i], triggers: [...e.triggers], retriggeredSeq: e.seq };
        if (s.plan === s.plans[i]) s.plan = corrected;
        s.plans[i] = corrected;
      }
    } else if (e.type === 'adr.status') {
      const prev = s.adrs.get(e.id) ?? {};
      s.adrs.set(e.id, {
        ...prev,
        first: prev.first ?? { source: e.source, schema: e.schema, by: e.by, note: e.note }, // 구형 ref 이관 결함 판정용(첫 이벤트 보존)
        id: e.id,
        file: e.file ?? prev.file,
        status: e.status,
        statusSeq: e.seq,
        supersededBy: e.superseded_by ?? prev.supersededBy,
        acceptedSeq: e.status === 'accepted' ? e.seq : prev.acceptedSeq,
        snapshot: e.snapshot ?? prev.snapshot ?? `adr/${e.id}.md`,
        sha256: e.sha256 ?? prev.sha256,
      });
    } else if (e.type === 'adr.impact') {
      const a = s.adrs.get(e.id);
      if (a) Object.assign(a, { impact: e.impact, impactReason: e.reason, impactBy: e.by, impactSeq: e.seq });
    } else if (e.type === 'inbox.triage') {
      for (const r of e.refs ?? [e.ref]) s.triaged.add(r);
    }
  }
  return s;
}

// 이 CLI가 처리하는 이벤트 종류. validateEvents의 case와 같아야 한다.
export const EVENT_TYPES = new Set(['directive.add', 'directive.amend', 'directive.status', 'order.set', 'plan.revise', 'plan.retrigger', 'adr.status', 'adr.impact', 'inbox.triage']);
export const unknownEventCount = (events) => events.filter((e) => !EVENT_TYPES.has(e.type) || (e.schema ?? 0) > MAX_SCHEMA).length;

// 원장 전체를 처음부터 다시 검증한다. CLI를 우회해 손으로 추가한 줄도 여기서 걸린다.
// warns를 주면 이 CLI가 검증할 수 없는 더 새 형식 이벤트를 거기에 알린다(ERROR로 올리지 않는다).
export function validateEvents(events, warns = null) {
  const errs = [];
  let future = 0;
  const seen = new Set();
  const dirs = new Map();
  const adrs = new Map();
  let lastSeq = 0;
  let lastRev = 0;
  const revs = new Set();
  const consumed = new Set();
  let protocol = 0;
  for (const e of events) {
    const at = `#${e.seq ?? '?'}(${e.type ?? '?'})`;
    if ((e.schema ?? 0) < protocol) errs.push(`${at}: 원장 프로토콜이 내려갔다. 모든 작업트리의 CLI를 갱신한다.`);
    protocol = Math.max(protocol, e.schema ?? 0);
    if (!Number.isInteger(e.seq) || e.seq !== lastSeq + 1) errs.push(`${at}: seq는 1씩 증가해야 한다(직전 ${lastSeq}).`);
    lastSeq = e.seq;
    if (!e.ts || Number.isNaN(Date.parse(e.ts))) errs.push(`${at}: ts 없음.`);
    if ((e.schema ?? 0) > MAX_SCHEMA) {
      future++;
      continue;
    }
    const needUser = (why) => {
      if (e.by !== 'user' || !String(e.quote ?? '').trim()) errs.push(`${at}: ${why}는 사용자 원문(by=user, quote)이 필요하다.`);
      if (e.schema >= 3 && (!e.approval?.ref || e.approval.origin !== 'user' || !/^[0-9a-f]{64}$/.test(e.approval.sha256 ?? ''))) errs.push(`${at}: ${why}는 포착된 승인 원문 증거가 필요하다.`);
    };
    switch (e.type) {
      case 'directive.add':
        if (!/^DIR-\d{3,}$/.test(e.id ?? '')) errs.push(`${at}: 지시 ID 형식은 DIR-001.`);
        if (seen.has(e.id)) errs.push(`${at}: ${e.id} 중복.`);
        if (!String(e.text ?? '').trim() || !String(e.source ?? '').trim()) errs.push(`${at}: 지시는 원문(text)과 출처(source)가 필요하다.`);
        seen.add(e.id);
        dirs.set(e.id, 'OPEN');
        break;
      case 'directive.amend':
        if (!dirs.has(e.id)) errs.push(`${at}: 없는 지시 ${e.id}.`);
        if (!String(e.text ?? '').trim() || !String(e.source ?? '').trim()) errs.push(`${at}: 변경 원문과 출처가 필요하다.`);
        break;
      case 'directive.status': {
        const cur = dirs.get(e.id);
        if (!cur) {
          errs.push(`${at}: 없는 지시 ${e.id}.`);
          break;
        }
        if (!STATUSES.has(e.status)) errs.push(`${at}: 알 수 없는 상태 ${e.status}.`);
        if (TERMINAL.has(cur)) errs.push(`${at}: ${e.id}는 이미 ${cur}(종결)이다. 다시 열려면 새 지시로 추가한다.`);
        if (USER_ONLY.has(e.status)) needUser(`${e.status} 전이`);
        if (e.status === 'DONE' && cur !== 'VERIFY') errs.push(`${at}: DONE은 VERIFY(증거 제출) 뒤에만 가능하다.`);
        if (e.status === 'VERIFY' && !String(e.evidence ?? '').trim()) errs.push(`${at}: VERIFY는 증거(evidence)가 필요하다.`);
        if (e.status === 'BLOCKED' && (!String(e.blocker ?? '').trim() || !String(e.unblock ?? '').trim()))
          errs.push(`${at}: BLOCKED는 막힘 사유(blocker)와 해제 조건(unblock)이 필요하다.`);
        if (e.status === 'SUPERSEDED' && !String(e.superseded_by ?? '').trim()) errs.push(`${at}: SUPERSEDED는 superseded_by가 필요하다.`);
        dirs.set(e.id, e.status);
        break;
      }
      case 'order.set':
        needUser('순서 변경');
        for (const id of e.order ?? []) if (!dirs.has(id)) errs.push(`${at}: 없는 지시 ${id}.`);
        break;
      case 'plan.revise': {
        const before = lastRev;
        needUser('계획 개정 승인');
        if (before === 0 ? !(Number.isInteger(e.rev) && e.rev >= 1) : e.rev !== before + 1)
          errs.push(`${at}: 계획 revision은 ${before === 0 ? '1 이상(기존 계획 이관 시 현재 번호)' : before + 1}이어야 한다.`);
        lastRev = e.rev ?? lastRev;
        revs.add(e.rev);
        if (!REVISE_REASONS.has(e.reason)) errs.push(`${at}: 개정 사유는 ${[...REVISE_REASONS].join('|')} 중 하나.`);
        if (e.reason === 'BASELINE' && before !== 0) errs.push(`${at}: BASELINE은 첫 revision(기존 계획 이관)에만 쓴다.`);
        if (e.reason !== 'BASELINE' && (!Array.isArray(e.triggers) || e.triggers.length === 0)) errs.push(`${at}: 개정 트리거(지시·ADR ID)가 필요하다.`);
        for (const t of e.triggers ?? []) if (!dirs.has(t) && !adrs.has(t)) errs.push(`${at}: 트리거 ${t}가 원장에 없다.`);
        if (!e.snapshot || !/^[0-9a-f]{64}$/.test(e.sha256 ?? '')) errs.push(`${at}: 계획 스냅샷과 sha256이 필요하다.`);
        if (e.schema >= 3 && (!Array.isArray(e.adr_basis) || e.adr_basis.some((b) => !/^ADR-\d{3,}$/.test(b.id ?? '') || !Number.isInteger(b.accepted_seq) || b.accepted_seq >= e.seq || !/^[0-9a-f]{64}$/.test(b.sha256 ?? '')))) errs.push(`${at}: 계획 ADR 기준점(id·accepted_seq·sha256)이 필요하다.`);
        break;
      }
      case 'plan.retrigger':
        // 승인된 REV 스냅샷은 바꿀 수 없으므로 잘못 지정한 트리거만 사용자 승인으로 정정한다.
        // 정정한 트리거도 check가 본문 언급을 다시 검사하므로 오류를 숨기는 데 쓸 수 없다.
        needUser('계획 트리거 정정');
        if (!revs.has(e.rev)) errs.push(`${at}: 정정 대상 REV-${e.rev}가 원장에 없다.`);
        if (!Array.isArray(e.triggers) || e.triggers.length === 0) errs.push(`${at}: 정정 트리거(지시·ADR ID)가 필요하다.`);
        for (const t of e.triggers ?? []) if (!dirs.has(t) && !adrs.has(t)) errs.push(`${at}: 트리거 ${t}가 원장에 없다.`);
        if (!String(e.reason ?? '').trim()) errs.push(`${at}: 트리거 정정은 사유(reason)가 필요하다.`);
        if (e.approval?.ref && consumed.has(e.approval.ref)) errs.push(`${at}: 트리거 정정은 이미 분류·소비된 입력을 승인으로 다시 쓸 수 없다.`);
        break;
      case 'adr.status':
        if (!/^ADR-\d{3,}$/.test(e.id ?? '')) errs.push(`${at}: ADR ID 형식은 ADR-001(또는 ADR-0001).`);
        if (!ADR_STATUSES.has(e.status)) errs.push(`${at}: ADR 상태는 ${[...ADR_STATUSES].join('|')}.`);
        if (!adrs.has(e.id) && !e.file) errs.push(`${at}: 첫 ADR 이벤트는 file이 필요하다.`);
        if (e.status === 'superseded' && adrs.get(e.superseded_by) !== 'accepted') errs.push(`${at}: 대체하는 ${e.superseded_by}가 먼저 accepted여야 한다.`);
        if (e.schema >= 3 && ['accepted', 'superseded', 'rejected'].includes(e.status) && e.source !== 'migration') needUser('ADR 결정 확정');
        adrs.set(e.id, e.status);
        break;
      case 'adr.impact':
        if (!adrs.has(e.id)) errs.push(`${at}: 없는 ADR ${e.id}.`);
        if (e.impact !== 'none' || !String(e.reason ?? '').trim()) errs.push(`${at}: adr.impact는 impact=none과 사유가 필요하다(영향이 있으면 계획 개정으로 처리).`);
        if (e.schema >= 3) needUser('ADR 영향 없음 확정');
        break;
      case 'inbox.triage':
        if (!(e.ref || (Array.isArray(e.refs) && e.refs.length)) || !e.as) errs.push(`${at}: triage는 ref(또는 refs)와 as가 필요하다.`);
        for (const ref of e.refs ?? [e.ref]) consumed.add(ref);
        break;
      default:
        errs.push(`${at}: 알 수 없는 이벤트 ${e.type ?? '?'}. 이 원장은 더 새 CLI가 기록했다. 이 작업트리 .plan/bin/plan.mjs를 하네스 원본판으로 갱신한다.`);
    }
  }
  if (future) (warns ?? errs).push(`이 CLI(schema ${MAX_SCHEMA}까지)가 검증할 수 없는 더 새 형식 이벤트 ${future}건. CLI를 갱신한다(무결성 검사는 계속 적용된다).`);
  return errs;
}

// ---------- 캡슐 렌더(결정적) ----------
const oneLine = (t) => String(t ?? '').replace(/\s+/g, ' ').trim();
const cut = (t, n) => {
  const cps = Array.from(oneLine(t)); // 코드포인트 단위로 자른다(한글 바이트 절단 방지).
  return cps.length <= n ? cps.join('') : cps.slice(0, n).join('') + '…';
};

// 캡슐 단계. 앞에서부터 예산(2,048B) 안에 드는 첫 단계를 쓴다. 어느 단계도 지시를 빼거나 렌더를 실패시키지 않는다.
// 마지막 두 단계는 원문 대신 ID·건수와 조회 명령(`plan directive list`)을 남긴다. 제목·표지·규칙 줄은 모든 단계에서 같다.
export const CAPSULE_LEVELS = [
  { name: 'e70', excerpt: 70, blocked: true },
  { name: 'e40', excerpt: 40, blocked: true },
  { name: 'e20', excerpt: 20, blocked: true },
  { name: 'e0', excerpt: 0, blocked: true },
  { name: 'e0-nb', excerpt: 0, blocked: false },
  { name: 'ids', excerpt: 0, ids: true },
  { name: 'count', excerpt: 0, count: true },
];
const lastAmend = (d) => d.amendments.at(-1);
export function renderCapsule(state, level = CAPSULE_LEVELS[0]) {
  if (!level?.name) level = { name: `e${level?.excerpt ?? 70}`, excerpt: level?.excerpt ?? 70, blocked: true }; // 옛 호출({ excerpt }) 호환
  const short = level.ids || level.count;
  const L = [BEGIN, `## 계획 캡슐 · 공유 원장 #${state.planSeq} (모든 브랜치·작업트리 공통)`];
  if (state.plan) {
    const p = state.plan;
    const triggers = short ? `${(p.triggers ?? []).length}건` : (p.triggers ?? []).join(',') || '-';
    L.push(`계획: REV-${p.rev} ${short ? cut(p.file, 60) : p.file} sha:${p.sha256.slice(0, 8)} · 사유 ${p.reason} · 트리거 ${triggers}`);
  } else L.push('계획: 승인된 revision 없음 → 사용자 승인 후 `plan revise` 필요');
  const live = state.order.map((id) => state.directives.get(id)).filter((d) => d && !TERMINAL.has(d.status));
  const work = live.filter((d) => d.status !== 'VERIFY');
  const verify = live.filter((d) => d.status === 'VERIFY');
  L.push('사용자 지시(순서·범위·완료는 사용자만 바꾼다):');
  if (work.length === 0) L.push('- (열린 지시 없음)');
  else if (level.count) {
    const by = {};
    for (const d of work) by[d.status] = (by[d.status] ?? 0) + 1;
    L.push(`- 열린 지시 ${work.length}건(${Object.entries(by).map(([k, v]) => `${k} ${v}`).join('·')}), 1순위 ${work[0].id} ${work[0].status}. 원문·변경·순서는 \`plan directive list\``);
  } else if (level.ids) L.push(`- ${work.map((d) => `${d.id} ${d.status}${d.amendments.length ? `+변경${d.amendments.length}` : ''}`).join(', ')}. 원문·변경은 \`plan directive list\``);
  else
    work.forEach((d, i) => {
      const e = level.excerpt;
      let line = `${i + 1}. ${d.id} ${d.status}`;
      // 사용자 근거(인용·승인)가 있는 최신 변경이 있으면 그 문장을 보인다(원문은 `plan directive show`). 근거 없는 변경은 건수만.
      const bi = d.amendments.findLastIndex((a) => a.backed);
      const unbacked = d.amendments.filter((a, j) => j > bi && !a.backed).length;
      if (e > 0) line += bi >= 0 ? ` 「${cut(d.amendments[bi].text, e)}」(변경#${bi + 1})` : ` 「${cut(d.text, e)}」`;
      else if (bi >= 0) line += ` (변경#${bi + 1})`;
      if (unbacked) line += ` +변경${unbacked}(근거 없음)`;
      if (d.status === 'BLOCKED') line += level.blocked ? ` 막힘:${cut(d.blocker, 40)} 해제:${cut(d.unblock, 40)}` : ' 막힘';
      else if (d.next && e > 0) line += ` 다음:${cut(d.next, 40)}`;
      L.push(line);
    });
  if (verify.length) L.push(`완료 확인 대기(VERIFY, 사용자 선언 필요): ${level.count ? `${verify.length}건` : verify.map((d) => d.id).join(', ')}`);
  const pending = pendingAdrs(state);
  if (pending.length) L.push(`계획 미반영 결정: ${short ? `${pending.length}건` : pending.map((a) => a.id).join(', ')} → \`plan revise\` 또는 \`plan adr impact <ID>\` 필요`);
  const proposed = [...state.adrs.values()].filter((a) => a.status === 'proposed');
  if (proposed.length) L.push(`결정 대기 ADR(제안 상태, 사용자 수락·기각 필요): ${short ? `${proposed.length}건` : proposed.map((a) => a.id).join(', ')}`);
  L.push('규칙: ①순서·범위·완료는 사용자만 ②선택지 1번은 「지시대로 즉시 진행」, 막힘 증거 없는 지연안에 (권장) 금지 ③원장·캡슐·승인 계획은 `plan` CLI로만');
  L.push('④STATE·메모리·인계서에 원장에 없는 순서를 쓰지 않음 ⑤작업 폴더와 지시 대상이 다르면 먼저 알림 ⑥세션 끝 `plan check --close`');
  L.push(END);
  return L.join('\n') + '\n';
}

// 예산 안에 드는 첫 단계의 캡슐과 그 단계. 마지막 단계도 넘치면(계획 경로·규칙만으로 넘는 경우) 그대로 돌려주고 check가 알린다.
export function capsuleWithLevel(state) {
  for (const level of CAPSULE_LEVELS) {
    const text = renderCapsule(state, level);
    if (Buffer.byteLength(text, 'utf8') <= CAPSULE_BUDGET) return { text, level };
  }
  const level = CAPSULE_LEVELS.at(-1);
  return { text: renderCapsule(state, level), level, over: true };
}
export const renderCapsuleWithinBudget = (state) => capsuleWithLevel(state).text;

// accepted 이후의 계획 revision 트리거에도, 영향 없음 선언에도 없는 ADR = 계획이 결정 변경을 따라가지 못한 상태.
export function pendingAdrs(state) {
  return [...state.adrs.values()].filter((a) => {
    if (a.status !== 'accepted') return false;
    const acc = a.acceptedSeq ?? 0;
    const revised = state.plan?.adr_basis
      ? state.plan.adr_basis.some((b) => b.id === a.id && b.accepted_seq === acc && (!a.sha256 || b.sha256 === a.sha256))
      : state.plans.some((p) => p.seq > acc && (p.triggers ?? []).includes(a.id));
    const noImpact = a.impact === 'none' && a.impactBy === 'user' && (a.impactSeq ?? 0) > acc;
    return !revised && !noImpact;
  });
}

// ---------- ADR 파일 상태 ----------
const ADR_WORDS = { 확정: 'accepted', accepted: 'accepted', 승인: 'accepted', 채택: 'accepted', 수락: 'accepted', 수락됨: 'accepted', proposed: 'proposed', 제안: 'proposed', superseded: 'superseded', 대체: 'superseded', 대체됨: 'superseded', deprecated: 'deprecated', 폐기: 'deprecated', rejected: 'rejected', 기각: 'rejected' };
const STATUS_LINE = /^(\s*(?:[-*]\s*)?(?:\*\*)?(?:status|상태)(?:\*\*)?\s*[:：.]\s*(?:\*\*)?\s*)([A-Za-z가-힣]+)(.*)$/im;
// 인식 가능한 상태면 표준 값, 상태 줄이 없거나 자유 문장("재검토 필요", "단계적 교체 결정")이면 null.
const STATUS_HEADING = /^#{2,4}\s*(?:status|상태)\.?\s*\n+\s*(?:[-*]\s*)?(?:\*\*)?([A-Za-z가-힣]+)/im; // "## 상태." 다음 줄에 값을 쓰는 형식
export function adrFileStatus(text) {
  const m = String(text).match(STATUS_LINE) ?? String(text).match(STATUS_HEADING);
  if (!m) return null;
  const w = (m[2] ?? m[1]).toLowerCase();
  return ADR_WORDS[w] ?? ADR_WORDS[w.replace(/됨$/, '')] ?? null;
}
export function adrStatusRaw(text) {
  return (String(text).match(STATUS_LINE)?.[0] ?? '').trim().slice(0, 60);
}
function setAdrFileStatus(file, status, note) {
  const text = fs.readFileSync(file, 'utf8');
  if (!note && adrFileStatus(text) === status) return text; // 이미 같은 상태(한국어 표기 포함)면 파일을 건드리지 않는다.
  const next = adrFileStatus(text) !== null && STATUS_LINE.test(text)
    ? text.replace(STATUS_LINE, (_, pre) => `${pre}${status}${note ? ` ${note}` : ''}`)
    : text.replace(/^(# .*\n)/, `$1\nStatus: ${status}${note ? ` ${note}` : ''}\n`);
  fs.writeFileSync(file, next);
  return next;
}
const adrDecisionBody = (text) => text.replace(STATUS_LINE, '').replace(/^#{2,4}\s*(?:status|상태)\.?\s*\n+[^\n]*\n?/im, '');
// 구형 하네스의 `adr import --ref`는 git 출력을 trimEnd해 스냅샷의 끝 줄바꿈이 빠졌다. 그 ADR의 첫 이벤트가 이관이고 브랜치 표기가 있을 때만 결함으로 인정한다.
function legacyRefImport(a) {
  const f = a?.first;
  if (!f) return false;
  const note = String(f.note ?? '');
  const migrated = f.source === 'migration' || (f.schema === undefined && f.by === 'agent' && note.startsWith('import'));
  return migrated && note.includes('(브랜치 ') && note.includes('에만 있음)');
}
// 구형 결함: 파일 바이트가 정확히 스냅샷 + "\n".
export function legacyRefImportNewline(a, fileBuf, snapBuf) {
  return legacyRefImport(a) && !!fileBuf && !!snapBuf && fileBuf.length === snapBuf.length + 1 && fileBuf[fileBuf.length - 1] === 0x0a && fileBuf.subarray(0, -1).equals(snapBuf);
}
// 확정 ADR 본문 비교(상태 줄 제외). 구형 ref 이관 ADR은 끝 줄바꿈 1개 차이를 같은 본문으로 본다.
function sameDecision(a, oldBuf, newBuf) {
  const o = adrDecisionBody(oldBuf.toString('utf8'));
  const n = adrDecisionBody(newBuf.toString('utf8'));
  return o === n || (legacyRefImport(a) && n === o + '\n');
}

// ---------- AGENTS.md 규칙 블록 ----------
export function withRules(agents) {
  if (agents.includes(RULES_BEGIN)) return agents;
  if (!agents.trim()) return RULES_BLOCK + '\n';
  const lines = agents.split('\n');
  const at = /^#\s/.test(lines[0]) ? 1 : 0; // 첫 제목 바로 아래. 파일 끝은 Codex 32KiB 상한에서 먼저 잘리고, 중간은 주의가 약하다.
  return [...lines.slice(0, at), ...(at ? [''] : []), RULES_BLOCK, '', ...lines.slice(at)].join('\n').replace(/\n{3,}/g, '\n\n');
}

// 범위 표기를 찾는다. 두 형태만 범위로 본다.
// 1) 양 끝 접두어: "DIR-015~DIR-018", "DIR-015 - DIR-018", "DIR-015—DIR-018". 구분자는 ~ – — -(앞뒤 공백 허용), 시작 ≤ 끝.
// 2) 끝 번호에 접두어 없음: "DIR-015~018", "DIR 015–018", "DIR-015-018". 구분자는 공백 없는 ~ – -, 양 끝 자릿수가 같고
//    시작 ≤ 끝이며 폭이 MAX_BARE_RANGE 이하. 공백 뒤 맨 숫자("DIR-015 – 300문항", "DIR-016 — 2026년")나 폭이 넓은
//    번호("DIR-015-300")는 산문·다른 숫자일 수 있어 범위로 보지 않는다(미반영 지시를 언급으로 오인하지 않는다).
const MAX_BARE_RANGE = 50;
function inRange(body, prefix, n) {
  const both = new RegExp(`${prefix}[\\s_-]?(\\d{3,4})\\s*[~–—-]\\s*${prefix}[\\s_-]?(\\d{3,4})(?!\\d)`, 'gi');
  for (const r of body.matchAll(both)) {
    const lo = Number(r[1]);
    const hi = Number(r[2]);
    if (lo <= hi && n >= lo && n <= hi) return true;
  }
  const bare = new RegExp(`${prefix}[\\s_-]?(\\d{3,4})[~–-](\\d{3,4})(?!\\d)`, 'gi');
  for (const r of body.matchAll(bare)) {
    if (r[1].length !== r[2].length) continue;
    const lo = Number(r[1]);
    const hi = Number(r[2]);
    if (lo <= hi && hi - lo <= MAX_BARE_RANGE && n >= lo && n <= hi) return true;
  }
  return false;
}

// 본문이 ID를 언급하는지. 더 긴 번호의 일부("DIR-0150" 안의 "DIR-015")는 언급이 아니다.
// ADR은 "ADR-0014", "ADR 0014", "0014-파일명"처럼 번호만 쓴 표기도 인정한다.
export function mentions(body, id) {
  const exact = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (new RegExp(`(^|[^A-Za-z0-9])${exact}(?![0-9])`).test(body)) return true;
  const d = id.match(/^DIR-(\d{3,4})$/);
  if (d) return inRange(body, 'DIR', Number(d[1]));
  const m = id.match(/^ADR-(\d{3,4})$/);
  if (!m) return false;
  if (new RegExp(`(ADR[\\s_-]?${m[1]}\\b|(^|[^0-9])${m[1]}-[a-z])`, 'i').test(body)) return true;
  return inRange(body, 'ADR', Number(m[1]));
}

// ---------- 검사 ----------
export function check(P, { close = false } = {}) {
  const errors = [];
  const warns = [];
  const { events, raw, errors: parseErrs, fromRef } = readLedger(P);
  errors.push(...parseErrs);
  if (parseErrs.length) return { errors, warns };
  errors.push(...validateEvents(events, warns));
  const state = fold(events);
  if (!fromRef && !events.some((e) => (e.schema ?? 0) >= WRITE_SCHEMA)) {
    const ws = writeSchemaFor(P, events);
    if (ws.schema < WRITE_SCHEMA) warns.push(`옛 판 CLI의 쓰기 차단(schema ${WRITE_SCHEMA})이 아직 꺼져 있다: ${ws.why}. 새 판을 기본 브랜치에 반영하면 다음 기록부터 자동으로 켜진다.`);
  }

  // 1) 추가 전용: 작업 원장 = 이력 ref 최신본이어야 한다. 이력 자체도 직전 스냅샷의 연장이어야 한다.
  let refLedger = null;
  let parentLedger = null;
  try {
    refLedger = refFile(P, 'ledger.jsonl');
    parentLedger = refLedger ? refFile(P, 'ledger.jsonl', `${REF}~1`) : null;
  } catch (e) {
    errors.push(`${e.message} 추가 전용 검사를 하지 못했다.`);
  }
  if (refLedger && !fromRef && !raw.equals(refLedger)) {
    if (raw.length > refLedger.length && raw.subarray(0, refLedger.length).equals(refLedger)) errors.push('CLI 밖에서 원장에 줄이 추가됐다. 추가분을 지우고(`plan restore`) plan 명령으로 다시 기록한다.');
    else errors.push('원장이 기록 이력(refs/plan/ledger) 대비 추가 전용이 아니다(삭제·수정). `plan restore`로 이력본을 복구한다.');
  }
  if (refLedger && parentLedger && !refLedger.subarray(0, parentLedger.length).equals(parentLedger)) errors.push('이력 ref가 재작성됐다(직전 스냅샷의 연장이 아님). `git reflog refs/plan/ledger`로 확인한다.');

  // 2) 승인 계획 스냅샷 불변, 본문이 트리거를 언급하는지, 작업 사본이 다른지.
  for (const p of state.plans) {
    const buf = readSnap(P, p.snapshot);
    if (!buf) {
      errors.push(`REV-${p.rev} 스냅샷 ${p.snapshot} 없음.`);
      continue;
    }
    if (sha256(buf) !== p.sha256) errors.push(`REV-${p.rev} 승인 계획 스냅샷이 승인 후 바뀌었다. 새 revision으로 개정한다.`);
    const body = buf.toString('utf8');
    for (const t of p.triggers ?? []) if (!mentions(body, t)) errors.push(`REV-${p.rev} 계획 본문이 트리거 ${t}를 언급하지 않는다(결정이 계획에 반영되지 않음).`);
    const wc = path.join(P.top, p.file);
    // 최신 승인본과 다른 계획 파일 = 승인되지 않은 계획 변경. 세션 중에는 경고, 세션 종료 때는 막는다(사용자 승인 → plan revise, 또는 되돌림).
    const latestForFile = [...state.plans].reverse().find((q) => q.file === p.file);
    if (p === latestForFile && fs.existsSync(wc) && sha256(fs.readFileSync(wc)) !== p.sha256)
      (close ? errors : warns).push(`${p.file}이 승인본 REV-${p.rev}와 다르다(승인되지 않은 계획 변경). 사용자 승인을 받아 \`plan revise --file ${p.file}\`로 새 revision을 등록하거나 되돌린다.`);
  }

  // 3) ADR: 현재 브랜치에 파일이 있으면 상태 줄이 원장과 같아야 하고, 없으면 다른 브랜치에만 있는 결정이다.
  for (const e of events.filter((e) => e.type === 'adr.status' && e.snapshot && e.sha256)) {
    const snap = readSnap(P, e.snapshot);
    if (!snap || sha256(snap) !== e.sha256) errors.push(`${e.id} #${e.seq} ADR 스냅샷이 기록 시점과 다르다.`);
  }
  for (const a of state.adrs.values()) {
    const snap = readSnap(P, a.snapshot);
    const refSnap = gitBuf(['show', `${REF}:${a.snapshot}`], P.top);
    if (snap && refSnap && !snap.equals(refSnap)) errors.push(`${a.id} ADR 스냅샷이 이력 ref와 다르다.`);
    if (!snap) errors.push(`${a.id} ADR 스냅샷 없음(${a.snapshot}).`);
    if (a.impact === 'none' && a.impactBy !== 'user') warns.push(`${a.id} 과거 에이전트의 영향 없음 선언은 사용자 확정이 없어 계획 반영으로 인정하지 않는다.`);
    const f = path.join(P.top, a.file ?? '');
    if (!a.file || !fs.existsSync(f)) {
      warns.push(`${a.id}(${a.status})가 현재 브랜치에 없다(${a.file}). 다른 브랜치에서 결정됐다 → 정본 브랜치로 병합한다.`);
      continue;
    }
    const fileBuf = fs.readFileSync(f);
    const text = fileBuf.toString('utf8');
    if (snap && ['accepted', 'rejected', 'superseded'].includes(a.status) && !Buffer.from(text).equals(snap)) {
      if (legacyRefImportNewline(a, fileBuf, snap)) warns.push(`${a.id} 구형 ref 이관 스냅샷과 끝 줄바꿈 1바이트만 다르다(하네스 이관 결함, 결정 내용 동일).`);
      else (close ? errors : warns).push(`${a.id} 확정 ADR 본문이 기록 스냅샷과 다르다. 결정 변경은 새 ADR로 대체하고 검증 기록은 별도 문서에 남긴다.`);
    }
    const fileStatus = adrFileStatus(text);
    if (fileStatus === null) warns.push(`${a.id} 파일 상태 줄이 없거나 인식할 수 없다(${adrStatusRaw(text) || '없음'}). 원장 상태 ${a.status} 기준. 사용자 확인 후 \`plan adr accept|propose\`로 표기를 맞춘다.`);
    else if (fileStatus !== a.status) errors.push(`${a.id} 파일 상태(${fileStatus ?? '없음'})가 원장(${a.status})과 다르다. \`plan adr\` 로만 바꾼다.`);
  }

  // 4) ADR → 계획 반영.
  for (const a of pendingAdrs(state)) (close ? errors : warns).push(`${a.id}가 현재 계획(REV-${state.plan?.rev ?? 0}) 이후 accepted 됐지만 계획에 반영되지 않았다.`);
  if (state.plan && !state.plan.adr_basis) warns.push(`REV-${state.plan.rev}는 구형 계획으로 ADR 기준점(adr_basis)이 없다. 다음 승인 개정에서 기준점을 명시한다(기존 원장 재작성 금지).`);

  // 5) 캡슐 예산·완전성·신선도(작업트리 사본은 생성물이라 낡으면 경고). 예산 때문에 줄인 단계는 WARN(커밋·턴 종료를 막지 않는다).
  const { text: capsule, level, over } = capsuleWithLevel(state);
  if (level.name !== CAPSULE_LEVELS[0].name) warns.push(`캡슐을 줄였다(단계 ${level.name}${over ? ', 마지막 단계도 예산 초과' : ''}). 지시 원문·변경이 캡슐에 다 들어가지 않는다. 사용자와 병합·종결을 결정하고, 원문은 \`plan directive list\`로 본다.`);
  if (!level.count) for (const d of state.directives.values()) if (!TERMINAL.has(d.status) && !capsule.includes(d.id)) errors.push(`캡슐에 열린 지시 ${d.id}가 없다.`);
  if (installed(P)) {
    const cur = fs.existsSync(P.capsule) ? fs.readFileSync(P.capsule, 'utf8') : null;
    if (cur !== capsule) warns.push(`${CAPSULE_REL}가 원장보다 낡았다(다른 세션이 기록함). \`plan render\` 로 갱신한다.`);
  }

  // 6) 진입 문서: AGENTS.md 규칙 블록, 크기, Claude가 AGENTS.md·캡슐을 불러오는지.
  const agentsFile = path.join(P.top, 'AGENTS.md');
  if (!fs.existsSync(agentsFile)) errors.push('AGENTS.md 없음(모든 도구가 읽는 공통 진입점).');
  else {
    const agents = fs.readFileSync(agentsFile, 'utf8');
    if (!agents.includes(RULES_BEGIN)) errors.push('AGENTS.md에 PLAN-RULES 블록이 없다. `plan init`으로 넣는다.');
    const size = Buffer.byteLength(agents);
    if (size > 32 * 1024) errors.push(`AGENTS.md ${size}B > 32KiB(Codex 기본 project_doc_max_bytes). 뒷부분이 잘린다.`);
    else if (size > 12 * 1024) warns.push(`AGENTS.md ${size}B. 진입 문서는 짧게(지도 역할) 유지한다.`);
  }
  const claudeFile = path.join(P.top, 'CLAUDE.md');
  if (fs.existsSync(claudeFile)) {
    const c = fs.readFileSync(claudeFile, 'utf8');
    if (!/^@AGENTS\.md\s*$/m.test(c)) errors.push('CLAUDE.md가 @AGENTS.md를 불러오지 않는다(링크만으로는 Claude가 AGENTS.md를 읽지 않는다).');
    if (!/^@\.plan\/CAPSULE\.md\s*$/m.test(c)) warns.push('CLAUDE.md가 @.plan/CAPSULE.md를 불러오지 않는다(압축 뒤 캡슐 재적재가 훅에만 의존).');
  }

  // 7) 세션 종료 시 미분류 사용자 입력 0. 입력함의 깨진 줄은 사용자 입력일 수 있으므로 알린다.
  const corrupt = [];
  listInboxAll(P, corrupt);
  if (corrupt.length) warns.push(`입력함에 읽을 수 없는 줄 ${corrupt.length}개(${corrupt.slice(0, 5).join(', ')}${corrupt.length > 5 ? ' …' : ''}). 원문을 확인해 필요하면 \`plan capture --text\`로 다시 남긴다(파일은 고치지 않는다).`);
  const inbox = listInbox(P);
  const untriaged = inbox.filter((x) => !state.triaged.has(x.id));
  if (untriaged.length) (close ? errors : warns).push(`미분류 사용자 입력 ${untriaged.length}건. \`plan triage --list\` 로 분류한다.`);

  // 8) "사용자 승인" 인용이 실제 입력에 있었는지(지어낸 승인 탐지). inbox는 로컬 전용이라 CI에서는 건너뛴다.
  // 과거 승인 증거 대조는 저장된 origin 그대로(재분류로 ERROR가 새로 생기지 않는다). 재분류 결과는 WARN으로만 알린다.
  const stored = listInboxAll(P).filter((r) => r.origin !== 'agent');
  const saidStored = stored.filter((x) => !x.origin || x.origin === 'user'); // 입력 포착 유무 판단은 기존과 같다
  const said = inbox.filter((x) => ['user', 'legacy'].includes(classifyRecord(x))).map((x) => String(x.prompt));
  const quoted = events.filter((e) => e.by === 'user' && e.quote);
  if (quoted.length && !saidStored.length) warns.push('입력 포착(inbox)이 없어 사용자 인용을 대조할 수 없다. 도구별 capture 훅을 설치한다.');
  else for (const e of quoted) {
    if (e.approval) {
      const r = stored.find((r) => r.id === e.approval.ref);
      if (r && (r.origin !== 'user' || sha256(r.prompt) !== e.approval.sha256 || !String(r.prompt).includes(e.quote))) errors.push(`#${e.seq} 승인 원문 증거가 포착 당시와 다르다.`);
      else if (r && classifyRecord(r) !== 'user') warns.push(`#${e.seq} 승인 원문이 재분류 결과 사용자 입력이 아니다(세션 간·에이전트 메시지).`);
      else if (!r && !fromRef) warns.push(`#${e.seq} 승인 원문 증거(${e.approval.ref})가 로컬 inbox에 없어 대조 불가.`);
    } else if (!said.some((s) => s.includes(e.quote))) warns.push(`#${e.seq} ${e.type} 사용자 인용 「${cut(e.quote, 30)}」이 포착된 입력에 없다(지어낸 승인 의심).`);
  }
  // 9) 다른 세션이 보낸 메시지(최근 7일 미분류). 사용자 입력이 아니므로 게이트에서 빼고 알리기만 한다.
  const weekAgo = Date.now() - 7 * 864e5;
  const peers = new Map();
  for (const x of listInboxAll(P)) {
    if (state.triaged.has(x.id) || !/^<cross-session-message(?:\s|>)/i.test(String(x.prompt).trimStart()) || !(Date.parse(x.ts) >= weekAgo)) continue;
    const tag = String(x.prompt).trimStart().split('>')[0];
    const m = tag.match(/\bfrom-name\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/);
    const name = m ? (m[1] ?? m[2] ?? m[3]) : '(이름 없음)';
    peers.set(name, (peers.get(name) ?? 0) + 1);
  }
  if (peers.size) {
    const total = [...peers.values()].reduce((a, b) => a + b, 0);
    const by = [...peers].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0]))).map(([n, c]) => `${n}: ${c}`).join(', ');
    warns.push(`다른 세션 메시지 ${total}건(${by}). 사용자 입력이 아니므로 승인·종료 게이트에서 제외했다.`);
  }
  // 10) 조각 루프(ADR-0005): 승인 기록을 읽을 때마다 다시 검사하고, 공유 상태 캐시·계약 파일과 대조한다.
  const ss = sliceState(P, events);
  errors.push(...ss.errors);
  warns.push(...ss.warns);
  const cacheErr = sliceCacheProblem(P, ss);
  if (cacheErr) errors.push(cacheErr);
  const cd = coreDelayProblems(P, events, state);
  errors.push(...cd.errors);
  warns.push(...cd.warns);
  const wc = weeklyCloseState(P, events);
  errors.push(...wc.errors);
  warns.push(...wc.warns);
  // 예산 소진은 check에서는 WARN이다(Stop은 막지 않는다). 차단은 precommit만 한다(사용자 결정 fecf90232cd4).
  if (budgetHit(ss)) warns.push(exhaustedMsg(ss.active, ss.usage));
  if (ss.active) {
    const f = path.join(P.top, ss.active.path);
    if (!fs.existsSync(f)) warns.push(`진행 중 조각 ${ss.active.id}의 계약 파일 ${ss.active.path}이 이 checkout에 없다(다른 브랜치에서 시작했다).`);
    else {
      const text = fs.readFileSync(f, 'utf8');
      if (sha256(contractCore(text)) !== ss.active.contract) warns.push(`진행 중 조각 ${ss.active.id}의 계약 파일 ${ss.active.path}이 시작 승인 뒤 바뀌었다(갭 목록·종료 분류 밖). 바뀐 계약은 사용자 재승인이 필요하다.`);
      // 세션 종료 점검에서는 허용 경로 밖 변경을 목록으로만 알린다(차단은 slice close가 한다).
      const changed = close && ss.switches.scope !== 'off' ? changedSince(P, ss.active.commit) : null;
      const c = changed && parseContract(text);
      const outside = c?.allowed.length ? outOfScope(P, ss.active, c, changed) : [];
      if (outside.length) warns.push(`조각 ${ss.active.id} 허용 경로 밖 변경 ${outside.length}건: ${outside.slice(0, 10).join(', ')}${outside.length > 10 ? ' …' : ''}. 닫을 때 종료 분류 unrequested에 적고 사용자 승인(「${ss.active.id} 범위 밖 승인」)을 받거나 되돌린다.`);
    }
  }
  return { errors, warns, state };
}

