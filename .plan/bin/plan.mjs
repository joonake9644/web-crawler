export const classOf = (classes, p) => Object.keys(classes).find((k) => classes[k].some((g) => globMatch(g, p))) ?? 'product';
// 시작 커밋 이후 이 브랜치·작업트리의 변경 경로(커밋·미커밋·추적 안 된 새 파일). 시작 커밋이 이 HEAD 계열에 없으면 null.
// 경로는 -z로 받는다(git의 경로 인용 때문에 한글 경로를 범위 밖으로 오판하지 않게, 구현 검토 r1 Codex 5).
// 시작 커밋이 rebase·amend로 HEAD 계열에서 빠졌으면(구현 검토 r1 Opus M4) 기본 브랜치 기준으로 판정하고 fallback에 그 ref를 남긴다.
// 기본 브랜치에서 일하면 판정하지 않는다(null).
const zlist = (out) => (out === null ? null : out.split('\0').filter(Boolean));
export function changedSince(P, commit, at = null) {
  const untracked = zlist(git(['ls-files', '-z', '--others', '--exclude-standard'], P.top));
  const anc = spawnSync('git', ['merge-base', '--is-ancestor', commit, 'HEAD'], { cwd: P.top, stdio: 'ignore' });
  if (anc.status === 0) {
    const diff = zlist(git(['diff', '--name-only', '-z', '--no-renames', commit], P.top));
    if (diff === null || untracked === null) return null;
    return Object.assign([...new Set([...diff, ...untracked])].sort(), { fallback: null });
  }
  const branch = git(['symbolic-ref', '--quiet', '--short', 'HEAD'], P.top);
  const base = defaultBranchCli(P).ref;
  if (!base || !branch || branch === base || base.endsWith(`/${branch}`)) return null;
  // 시작 커밋 대비 바뀌었으면서 기본 브랜치와도 다른 경로만 이 브랜치의 변경이다(rebase로 들어온 기본 브랜치 변경은 빠지고,
  // amend로 더한 파일은 들어간다. 작성 시각을 쓰지 않는다, 재확인 1회차 Codex R2).
  const fromStart = zlist(git(['diff', '--name-only', '-z', '--no-renames', commit, 'HEAD'], P.top));
  const fromBase = zlist(git(['diff', '--name-only', '-z', '--no-renames', base, 'HEAD'], P.top));
  const work = zlist(git(['diff', '--name-only', '-z', '--no-renames', 'HEAD'], P.top));
  if (fromStart === null || fromBase === null || work === null || untracked === null) return null;
  const differs = new Set(fromBase);
  return Object.assign([...new Set([...fromStart.filter((x) => differs.has(x)), ...work, ...untracked])].sort(), { fallback: base });
}
// 계약 허용 경로 밖 변경. 계약 파일 자신과 계획·하네스·세션 문서 분류는 자동 제외한다(방법론 4-4).
export function outOfScope(P, s, c, changed) {
  const classes = energyClasses(P);
  const auto = ['plan', 'harness', 'session'].flatMap((k) => classes[k] ?? []);
  return changed.filter((p) => p !== s.path && !c.allowed.some((g) => globMatch(g, p)) && !auto.some((g) => globMatch(g, p)));
}
// 정해진 문구 비교: 앞뒤 공백과 끝의 「(권장)」만 뺀다. 반대 문장·덧붙인 말은 다른 문구다.
export const normPhrase = (s) => String(s ?? '').trim().replace(/\s*\(권장\)$/, '').trim();
// 승인 근거 입력의 공통 조건(방법론 4-3). 문제가 없으면 null.
export function approvalProblem(rec, phrase, { consumed = new Set(), after = null, before = null } = {}) {
  if (!rec) return '근거 입력이 입력함에 없다';
  const cls = classifyRecord(rec);
  if (!(cls === 'user' || (rec.kind === 'choice' && cls === 'unknown'))) return `근거 입력 ${rec.id}의 출처가 ${cls}다(직접 입력 또는 선택지 응답만 인정, 수동 capture --text는 근거가 아니다)`;
  if (normPhrase(rec.prompt) !== phrase) return `근거 입력 문구 「${cut(rec.prompt, 40)}」가 정해진 형식 「${phrase}」과 다르다`;
  if (consumed.has(rec.id)) return `근거 입력 ${rec.id}는 이미 분류·승인에 쓴 입력이다(1회 사용)`;
  if (after && !(Date.parse(rec.ts) >= Date.parse(after))) return `근거 입력이 ${after} 뒤 입력이 아니다`;
  if (before && Date.parse(rec.ts) > Date.parse(before)) return '근거 입력이 기록 시각보다 뒤다';
  return null;
}
const SLICE_START = /^slice:([^:]+):start:budget=(\d+):commit=([0-9a-f]{7,64}):contract=([0-9a-f]{64})(?::cfg=([0-9a-f]{16}))?:path=([^:]*):at=(.+)$/;
const SLICE_EXTEND = /^slice:([^:]+):extend:by=([1-9]\d?):at=(.+)$/;
const SLICE_CARRY = /^slice:([^:]+):carry:at=(.+)$/;
const SLICE_CLOSE = /^slice:([^:]+):close:commit=([0-9a-f]{7,64}):unreq=(\d+):at=(.+)$/;
const SLICE_SWITCH = /^slice:@switch:([a-z-]+):(block|warn|off):at=(.+)$/; // @는 조각 ID에 못 쓰므로 조각 기록과 겹치지 않는다
// 장치 스위치(ADR-0005 10항, 설계 재확인 LOW L3). 안내 장치(bloat·plan-missing)는 막지 않으므로 block이 없다.
export const SWITCH_DEVICES = { budget: ['block', 'warn', 'off'], scope: ['block', 'warn', 'off'], 'core-delay': ['block', 'warn', 'off'], bloat: ['warn', 'off'], 'plan-missing': ['warn', 'off'] };
export const DEFAULT_SWITCHES = { budget: 'block', scope: 'block', 'core-delay': 'block', bloat: 'warn', 'plan-missing': 'warn' };
// 세션 계수(방법론 4-2, 사용자 결정 5a3a8cd7820a): 조각 시작 뒤 입력함에 사용자 입력(직접 입력·선택지 응답)이 있었던
// 서로 다른 (도구, 대화 ID, 서울 날짜)의 수. 읽기 전용 계산이다(check·check --close에 계수를 걸지 않는다).
export const seoulDate = (ts) => new Date(Date.parse(ts) + 9 * 36e5).toISOString().slice(0, 10);
export const sessionKey = (r) => `${r.tool ?? '?'}|${r.session ?? '?'}|${seoulDate(r.ts)}`;
const countable = (r) => {
  const c = classifyRecord(r);
  return c === 'user' || (r.kind === 'choice' && c === 'unknown');
};
// 예산 = 시작 예산 + 승인된 연장. 소진 시각 = 예산을 넘는 세션(N+1번째)의 첫 입력 시각. upto 이후 입력은 세지 않는다.
export function sliceUsage(recs, s, upto = s.ended ?? null) {
  const total = s.budget + s.extensions.reduce((a, x) => a + x.by, 0);
  const keys = new Set();
  let exhaustedAt = null;
  for (const r of recs) {
    if (!(Date.parse(r.ts) > Date.parse(s.at))) continue;
    if (upto && Date.parse(r.ts) > Date.parse(upto)) break;
    keys.add(sessionKey(r));
    if (!exhaustedAt && keys.size > total) exhaustedAt = r.ts;
  }
  return { used: keys.size, total, exhaustedAt };
}
// 원장에서 조각 상태를 다시 계산한다. 승인 조건을 만족하지 않는 기록은 errors에 넣고 상태에 반영하지 않는다.
// 입력함이 아예 없는 환경(CI 클론 등)은 근거를 대조할 수 없어 WARN으로 두고 기록대로 반영한다(ADR-0005 L1).
export function sliceState(P, events) {
  const out = { slices: new Map(), active: null, usage: null, switches: { ...DEFAULT_SWITCHES }, errors: [], warns: [] };
  const all = listInboxAll(P);
  const users = listInbox(P).filter(countable).sort((a, b) => Date.parse(a.ts) - Date.parse(b.ts));
  const consumed = new Set();
  for (const e of events) {
    if (e.type !== 'inbox.triage') continue;
    const refs = e.refs ?? [e.ref];
    const as = String(e.as ?? '');
    if (as.startsWith('slice:')) {
      const id = as.split(':')[1];
      const rec = all.find((r) => r.id === refs[0]);
      const proof = (phrase, after = null) => {
        if (!rec && all.length) return `근거 입력 ${refs[0]}가 입력함에 없다`;
        if (!rec) {
          out.warns.push(`#${e.seq} 조각 ${id} 승인: 입력함이 없어 근거 입력을 대조 불가(원장 기록대로 둔다).`);
          return null;
        }
        return approvalProblem(rec, phrase, { consumed, before: e.ts, after });
      };
      // 연장·이월: 진행 중 조각이고, 그 기록 시점에 예산이 소진됐고, 근거가 소진 뒤 입력이어야 한다.
      const afterExhaustion = (s, phrase) => {
        if (!s || s.status !== 'active') return '진행 중 조각이 아니다';
        const u = sliceUsage(users, s, e.ts);
        if (!u.exhaustedAt && all.length) return `예산이 소진되지 않았다(${u.used}/${u.total})`;
        return proof(phrase, u.exhaustedAt);
      };
      let why = null;
      let m;
      if ((m = as.match(SLICE_SWITCH))) {
        const [, dev, mode] = m;
        why = SWITCH_DEVICES[dev]?.includes(mode) ? proof(`${dev} ${mode}`) : `알 수 없는 장치·값 ${dev} ${mode}`;
        if (!why) out.switches[dev] = mode;
      } else if ((m = as.match(SLICE_START))) {
        const [, sid, budget, commit, contract, cfg, enc, at] = m;
        let rel = null;
        try {
          rel = decodeURIComponent(enc);
        } catch {}
        why = proof(`${sid} 시작 예산 ${Number(budget)}세션`);
        if (!why && rel === null) why = '계약 경로 형식 오류';
        if (!why && out.slices.has(sid)) why = '같은 조각 ID를 다시 시작했다';
        if (!why && out.active) why = `조각 ${out.active.id}가 진행 중이었다(WIP 1)`;
        if (!why) {
          out.active = { id: sid, status: 'active', budget: Number(budget), extensions: [], commit, contract, cfg: cfg ?? null, path: rel, at, seq: e.seq, ref: refs[0] };
          out.slices.set(sid, out.active);
        }
      } else if ((m = as.match(SLICE_EXTEND))) {
        const s = out.slices.get(m[1]);
        why = afterExhaustion(s, `${m[1]} ${Number(m[2])}세션 연장`);
        if (!why) s.extensions.push({ by: Number(m[2]), seq: e.seq, ref: refs[0] });
      } else if ((m = as.match(SLICE_CARRY))) {
        const s = out.slices.get(m[1]);
        why = afterExhaustion(s, `${m[1]} 이월`);
        if (!why) {
          Object.assign(s, { status: 'carried', ended: e.ts, endSeq: e.seq });
          out.active = null;
        }
      } else if ((m = as.match(SLICE_CLOSE))) {
        // 닫기: 소진된 조각은 닫지 못한다(연장·이월 없이 커밋 차단을 피하는 길을 막는다). 근거 입력은 범위 밖이 있으면
        // 「<ID> 범위 밖 승인」, 없으면 「<ID> 종료 승인」. 한계: 검사 명령 실행 결과는 읽을 때 다시 만들 수 없다(닫는 순간 CLI가 실행한다).
        const s = out.slices.get(m[1]);
        if (!s || s.status !== 'active') why = '진행 중 조각이 아니다';
        else {
          const u = sliceUsage(users, s, e.ts);
          if (u.exhaustedAt && out.switches.budget === 'block') why = `예산 소진(${u.used}/${u.total}) 뒤 연장·이월 없이 닫았다`;
          else why = proof(Number(m[3]) > 0 ? `${m[1]} 범위 밖 승인` : `${m[1]} 종료 승인`); // 닫기도 근거 사용자 입력이 있어야 한다(설계 3-0, 구현 검토 r1)
        }
        // 한계(구현 재확인 2회차 뒤 사용자 결정 「단순화」): 범위 판정은 닫는 순간 CLI가 작업 폴더까지 보고 한다. 읽을 때 커밋끼리 다시
        // 판정하면 작업 폴더에서 되돌리고 정상으로 닫은 조각까지 영구 ERROR가 됐다(Opus N1). 옛 CLI 사본으로 꾸민 unreq=0 닫기는
        // 사용자의 실제 「<ID> 종료 승인」 입력이 있어야 통과하며, 이 한계는 방법론 3-0에 적는다.
        if (!why) {
          Object.assign(s, { status: 'closed', ended: e.ts, endSeq: e.seq, endCommit: m[2] });
          out.active = null;
        }
      } else why = '알 수 없는 조각 기록 형식';
      if (why) out.errors.push(`#${e.seq} 조각 ${id} 기록이 승인 조건을 만족하지 않아 승인으로 치지 않는다: ${why}.`);
    }
    for (const r of refs) consumed.add(r);
  }
  if (out.active) out.usage = sliceUsage(users, out.active);
  return out;
}
