export function writeSliceCache(P, ss) {
  assertOwnLedger(P);
  const f = slicesFile(P);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  const tmp = `${f}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify({ schema: 1, note: '원장(refs/plan/ledger)에서 다시 만드는 캐시. 직접 고치지 않는다.', ...sliceView(ss) }, null, 2) + '\n');
  fs.renameSync(tmp, f);
}
// 잠금 안에서 최신 원장으로 다시 계산해 캐시를 쓴다(두 명령이 겹쳐 낡은 상태로 덮지 않게, 구현 검토 r1 Codex 4).
export const refreshSliceCache = (P) => withLock(P, () => writeSliceCache(P, sliceState(P, readLedger(P).events)));
// 캐시가 있으면 원장에서 다시 계산한 값과 같아야 한다(변조 탐지). 없으면 문제 아님(읽는 쪽이 다시 만든다).
export function sliceCacheProblem(P, ss) {
  const f = slicesFile(P);
  if (!fs.existsSync(f)) return null;
  let cur = null;
  try {
    cur = JSON.parse(fs.readFileSync(f, 'utf8'));
  } catch {}
  if (cur && JSON.stringify({ active: cur.active ?? null, switches: cur.switches ?? {}, slices: cur.slices ?? {} }) === JSON.stringify(sliceView(ss))) return null;
  return `조각 공유 상태 ${f}(state.json)가 원장 기록과 다르다. 직접 고치지 않는다. \`plan slice status\`로 원장에서 다시 만든다.`;
}

function sliceCmd(P, cwd, sub, arg, flags, out, pos3) {
  if (sub === 'status') {
    const ss = sliceState(P, readLedger(P).events);
    if (ss.slices.size || fs.existsSync(slicesFile(P))) refreshSliceCache(P);
    for (const e of ss.errors) process.stderr.write(`ERROR ${e}\n`);
    const rows = [...ss.slices.values()].map((s) => {
      const ext = s.extensions.reduce((a, x) => a + x.by, 0);
      const u = s === ss.active ? ` · 사용 ${ss.usage.used}/${ss.usage.total}${ss.usage.exhaustedAt ? ' 초과' : ''}` : '';
      return `${s.id} ${s.status} 예산 ${s.budget}${ext ? `+${ext}` : ''}세션${u} · 시작 ${s.at} · 커밋 ${s.commit.slice(0, 7)} · 계약 ${s.path}`;
    });
    const sw = Object.entries(ss.switches).map(([k, v]) => `${k}=${v}`).join(' ');
    return out([ss.active ? `진행 중 조각: ${ss.active.id}` : '(진행 중 조각 없음)', ...rows, `스위치: ${sw}`].join('\n'));
  }
  if (sub === 'switch') {
    // 장치 스위치는 「<장치> <값>」 정확한 사용자 입력으로만 바꾼다(방법론 4-3).
    const dev = arg;
    const mode = pos3;
    const ref = flags['approval-ref'];
    if (!SWITCH_DEVICES[dev]) throw new Error(`장치 식별자는 ${Object.keys(SWITCH_DEVICES).join(', ')} 중 하나다.`);
    if (!SWITCH_DEVICES[dev].includes(mode)) throw new Error(`${dev} 값은 ${SWITCH_DEVICES[dev].join('|')} 중 하나다.`);
    if (typeof ref !== 'string') throw new Error(`사용자가 AI 도구 입력창에 「${dev} ${mode}」를 그대로 입력한 기록의 ID를 \`--approval-ref\`로 준다.`);
    const phrase = `${dev} ${mode}`;
    const rec = listInbox(P).find((r) => r.id === ref);
    if (!rec) throw new Error(`근거 입력 ${ref}가 입력함에 없다.`);
    const at = new Date().toISOString();
    appendEvent(P, { type: 'inbox.triage', ts: at, refs: withDups(P, [ref]), as: `slice:@switch:${dev}:${mode}:at=${at}` }, [], (events) => {
      const ss = sliceState(P, events);
      if (ss.errors.length) throw new Error(`원장의 조각 기록 오류를 먼저 처리한다(\`plan check\`):\n${ss.errors.join('\n')}`);
      const why = approvalProblem(rec, phrase, { consumed: fold(events).triaged });
      if (why) throw new Error(`${why}.`);
    });
    refreshSliceCache(P);
    return out(`장치 ${dev} → ${mode}, 근거 입력 ${ref}.`);
  }
  if (sub === 'close') {
    // 종료 게이트(방법론 2절 ④): 시작 때 승인된 계약 핵심으로 검사 명령·허용 경로를 판정하고(구현 검토 r1 HIGH: 계약을 고쳐 게이트를
    // 우회하지 못하게), 종료 분류 네 칸, 허용 경로 밖 변경의 unrequested 기재, 검사 명령 직접 실행, 근거 사용자 입력을 확인한다.
    const id = arg;
    if (!id) throw new Error('사용법: plan slice close <ID> --approval-ref <입력 ID> [--timeout-sec N]');
    const ss = sliceState(P, readLedger(P).events);
    if (ss.errors.length) throw new Error(`원장의 조각 기록 오류를 먼저 처리한다(\`plan check\`):\n${ss.errors.join('\n')}`);
    const s = ss.active;
    if (s?.id !== id) throw new Error(`조각 ${id}는 진행 중이 아니다${s ? `(진행 중: ${s.id})` : ''}.`);
    if (budgetHit(ss) && ss.switches.budget === 'block') throw new Error(`조각 ${id} 예산이 소진된 상태(${ss.usage.used}/${ss.usage.total})에서는 닫지 않는다. 먼저 사용자 답으로 연장(「${id} <N>세션 연장」)하거나 이월(「${id} 이월」)한다.`);
    const f = path.join(P.top, s.path);
    if (!fs.existsSync(f)) throw new Error(`계약 파일 ${s.path}이 이 checkout에 없다. 조각을 시작한 브랜치에서 닫는다.`);
    const text = fs.readFileSync(f, 'utf8');
    if (sha256(contractCore(text)) !== s.contract)
      throw new Error(`계약 핵심(갭 목록·종료 분류 밖)이 시작 승인과 다르다(${s.path}). 시작 승인 계약으로 되돌린 뒤 닫는다(\`git show ${s.commit.slice(0, 7)}:${s.path}\`). 바꿔야 할 범위는 사용자에게 보고하고 새 조각 계약으로 승인받는다.`);
    if (s.cfg && gateConfigHash(P) !== s.cfg) throw new Error('범위 판정 설정(.plan/config.json energy.classes)이 조각 시작 뒤 바뀌었다. 시작 때 설정으로 되돌리거나, 바뀐 설정을 사용자에게 보고하고 결정을 받는다.');
    const c = parseContract(text); // 핵심이 승인본과 같으므로 검사·허용 경로는 승인된 내용이다. 종료 분류·갭은 지금 채운 것
    const cl = parseClosure(c.closure);
    const blank = CLOSURE_KEYS.filter((k) => cl[k] === null);
    if (blank.length) throw new Error(`종료 분류 칸이 비었다: ${blank.join(', ')}. 계약 「## 종료 분류」에 \`- missing: 없음\`처럼 네 칸(missing·partial·contradicts·unrequested)을 모두 적는다.`);
    const scope = ss.switches.scope;
    const judge = (when) => {
      const changed = changedSince(P, s.commit, s.at);
      if (!changed) throw new Error(`시작 커밋 ${s.commit.slice(0, 7)}이 이 브랜치 HEAD 계열에 없고, 기본 브랜치 기준으로도 판정하지 못했다. 조각을 시작한 기능 브랜치에서 닫는다.`);
      if (changed.fallback && when === 'before') process.stderr.write(`WARN 시작 커밋이 rebase·amend로 HEAD 계열에서 빠져, ${changed.fallback}에 없는 이 브랜치 커밋(조각 시작 뒤 작성) 기준으로 범위를 판정했다.\n`);
      const outside = c.allowed.length && scope !== 'off' ? outOfScope(P, s, c, changed) : [];
      return outside.filter((p) => !cl.unrequested.some((g) => g === p || globMatch(g, p)));
    };
    if (!c.allowed.length) process.stderr.write('WARN 계약에 허용 경로가 없어 범위 밖 변경을 판정하지 않았다(위험 등급 light).\n');
    const uncovered = judge('before');
    if (uncovered.length && scope === 'warn') process.stderr.write(`WARN 허용 경로 밖 변경이 종료 분류 unrequested에 없다: ${uncovered.join(', ')}(스위치 scope=warn이라 막지 않는다).\n`);
    else if (uncovered.length) throw new Error(`허용 경로 밖 변경이 종료 분류 unrequested에 없다: ${uncovered.join(', ')}. 되돌리거나 unrequested에 적고 사용자 승인(「${id} 범위 밖 승인」)을 받는다.`);
    // 닫기도 근거 사용자 입력이 있어야 한다(설계 3-0). 범위 밖이 있으면 「<ID> 범위 밖 승인」, 없으면 「<ID> 종료 승인」.
    const unreq = cl.unrequested.length && scope === 'block' ? cl.unrequested.length : 0;
    const phrase = unreq ? `${id} 범위 밖 승인` : `${id} 종료 승인`;
    const ref = flags['approval-ref'];
    if (typeof ref !== 'string') throw new Error(`${unreq ? `종료 분류 unrequested ${unreq}건이 있다. 사용자에게 보고하고, ` : '종료 결과(검사·종료 분류·남은 갭)를 사용자에게 보고하고, '}사용자가 AI 도구 입력창에 「${phrase}」를 그대로 입력한 기록의 ID를 \`--approval-ref\`로 준다.`);
    const rec = listInbox(P).find((r) => r.id === ref);
    if (!rec) throw new Error(`근거 입력 ${ref}가 입력함에 없다.`);
    const why0 = approvalProblem(rec, phrase, { consumed: fold(readLedger(P).events).triaged });
    if (why0) throw new Error(`${why0}.`);
    // 검사 명령은 CLI가 직접 실행한다(에이전트 보고를 믿지 않는다). 명령마다 시간 상한.
    const limit = Math.max(1, Number(flags['timeout-sec']) || 600) * 1000;
    const failed = [];
    for (const cmd of c.checks) {
      const r = spawnSync('sh', ['-c', cmd], { cwd: P.top, encoding: 'utf8', timeout: limit, maxBuffer: 64 << 20 });
      if (r.status !== 0 || r.error || r.signal) {
        const tail = `${r.stdout ?? ''}${r.stderr ?? ''}`.trim().split('\n').slice(-5).join('\n');
        failed.push(`\`${cmd}\` 종료 코드 ${r.status ?? r.signal ?? r.error?.code}${tail ? `\n${tail}` : ''}`);
      }
    }
    if (failed.length) throw new Error(`검사 명령 실패로 닫지 않았다:\n${failed.join('\n')}`);
    // 검사 명령이 만든 파일까지 다시 판정한다(구현 검토 r1 Codex 6).
    const after = judge('after');
    if (after.length && scope === 'block') throw new Error(`검사 명령 실행 뒤 허용 경로 밖 변경이 생겼다: ${after.join(', ')}. 검사 명령이 만드는 파일을 정리하거나 unrequested에 적고 사용자 승인을 받는다.`);
    const head = git(['rev-parse', '--verify', '-q', 'HEAD'], P.top);
    const at = new Date().toISOString();
    appendEvent(P, { type: 'inbox.triage', ts: at, refs: withDups(P, [rec.id]), as: `slice:${id}:close:commit=${head}:unreq=${unreq}:at=${at}` }, [], (events) => {
      const now = sliceState(P, events);
      if (now.active?.id !== id) throw new Error(`조각 ${id}는 진행 중이 아니다.`);
      if (budgetHit(now) && now.switches.budget === 'block') throw new Error(`조각 ${id} 예산이 소진됐다(${now.usage.used}/${now.usage.total}). 연장·이월 먼저.`);
      const why = approvalProblem(rec, phrase, { consumed: fold(events).triaged });
      if (why) throw new Error(`${why}.`);
    });
    refreshSliceCache(P);
    return out(`조각 ${id} 닫음: 검사 ${c.checks.length}건 통과, 종료 분류 missing ${cl.missing.length}·partial ${cl.partial.length}·contradicts ${cl.contradicts.length}·unrequested ${cl.unrequested.length}, 남은 갭 ${c.gaps.length}건(다음 조각 계약이나 정리 슬롯으로), 근거 입력 ${ref}.`);
  }
  if (sub === 'extend' || sub === 'carry') {
    const id = arg;
    const ref = flags['approval-ref'];
    const by = sub === 'extend' ? Number(flags.by) : null;
    if (!id || typeof ref !== 'string' || (sub === 'extend' && !(Number.isInteger(by) && by >= 1 && by <= 99)))
      throw new Error(`사용법: plan slice ${sub === 'extend' ? 'extend <ID> --by <1~99>' : 'carry <ID>'} --approval-ref <입력 ID>`);
    const phrase = sub === 'extend' ? `${id} ${by}세션 연장` : `${id} 이월`;
    const how = `예산 소진 뒤 사용자가 AI 도구 입력창에 「${phrase}」를 그대로 입력(또는 그 문구의 선택지를 선택)한 기록만 근거가 된다`;
    const rec = listInbox(P).find((r) => r.id === ref);
    if (!rec) throw new Error(`근거 입력 ${ref}가 입력함에 없다. ${how}.`);
    const at = new Date().toISOString();
    const as = sub === 'extend' ? `slice:${id}:extend:by=${by}:at=${at}` : `slice:${id}:carry:at=${at}`;
    appendEvent(P, { type: 'inbox.triage', ts: at, refs: withDups(P, [ref]), as }, [], (events) => {
      const ss = sliceState(P, events);
      if (ss.errors.length) throw new Error(`원장의 조각 기록 오류를 먼저 처리한다(\`plan check\`):\n${ss.errors.join('\n')}`);
      if (ss.active?.id !== id) throw new Error(`조각 ${id}는 진행 중이 아니다${ss.active ? `(진행 중: ${ss.active.id})` : ''}.`);
      if (!ss.usage.exhaustedAt) throw new Error(`조각 ${id} 예산이 아직 소진되지 않았다(${ss.usage.used}/${ss.usage.total}세션). 연장·이월은 소진 뒤 사용자 답으로만 한다.`);
      const why = approvalProblem(rec, phrase, { consumed: fold(events).triaged, after: ss.usage.exhaustedAt });
      if (why) throw new Error(`${why}. ${how}.`);
    });
    refreshSliceCache(P);
    const ss = sliceState(P, readLedger(P).events);
    return out(sub === 'extend' ? `조각 ${id} ${by}세션 연장(사용 ${ss.usage.used}/${ss.usage.total}), 근거 입력 ${ref}.` : `조각 ${id} 이월(종료), 근거 입력 ${ref}. 남은 일은 다음 조각 계약에 붙인다.`);
  }
  if (sub === 'start') {
    if (!arg) throw new Error('사용법: plan slice start <계약 파일> --approval-ref <입력 ID>');
    const abs = path.resolve(cwd, String(arg));
    const rel = path.relative(P.top, abs).split(path.sep).join('/');
    if (rel.startsWith('..') || path.isAbsolute(rel)) throw new Error(`계약 파일은 이 저장소 안에 둔다(${arg}).`);
    const buf = fs.readFileSync(abs);
    const c = parseContract(buf.toString('utf8'));
    const problems = contractProblems(c);
    const ref = flags['approval-ref'];
    if (typeof ref !== 'string') problems.push('`--approval-ref <입력 ID>`가 필요하다(사용자가 정해진 문구를 입력한 기록, `plan triage --list`).');
    if (problems.length) throw new Error(`계약·인자 오류로 시작하지 않았다:\n- ${problems.join('\n- ')}`);
    const phrase = `${c.id} 시작 예산 ${c.budget}세션`;
    const how = `사용자가 AI 도구 입력창에 「${phrase}」를 그대로 입력(또는 그 문구의 선택지를 선택)한 기록만 근거가 된다`;
    const rec = listInbox(P).find((r) => r.id === ref);
    if (!rec) throw new Error(`근거 입력 ${ref}가 입력함에 없다. ${how}.`);
    const head = git(['rev-parse', '--verify', '-q', 'HEAD'], P.top);
    if (!head) throw new Error('시작 커밋이 없다. 계약 파일을 커밋한 뒤 시작한다.');
    const contract = sha256(contractCore(buf.toString('utf8')));
    const at = new Date().toISOString();
    const as = `slice:${c.id}:start:budget=${c.budget}:commit=${head}:contract=${contract}:cfg=${gateConfigHash(P)}:path=${encodeURIComponent(rel)}:at=${at}`;
    appendEvent(P, { type: 'inbox.triage', ts: at, refs: withDups(P, [ref]), as }, [], (events) => {
      const ss = sliceState(P, events);
      if (ss.errors.length) throw new Error(`원장의 조각 기록 오류를 먼저 처리한다(\`plan check\`):\n${ss.errors.join('\n')}`);
      if (ss.active) throw new Error(`조각 ${ss.active.id}가 진행 중이다(WIP 1, 저장소 전체 공통). 먼저 그 조각을 닫거나 사용자 승인으로 이월한다.`);
      if (ss.slices.has(c.id)) throw new Error(`조각 ID ${c.id}는 이미 쓰였다. 새 ID로 계약을 쓴다.`);
      const why = approvalProblem(rec, phrase, { consumed: fold(events).triaged });
      if (why) throw new Error(`${why}. ${how}.`);
      // 시작 커밋의 계약이 승인 기준이다. 커밋되지 않았거나 바뀐 채로 시작하지 않는다(닫을 때 승인본을 다시 꺼낸다).
      if (git(['ls-files', '--error-unmatch', '--', rel], P.top) === null || git(['status', '--porcelain', '--', rel], P.top)) throw new Error(`계약 파일 ${rel}을 커밋한 뒤 시작한다(시작 커밋의 계약이 승인 기준이 된다).`);
    });
    refreshSliceCache(P);
    const after = sliceState(P, readLedger(P).events);
    // 넘김(방법론 2절 ⑤): 앞 조각 계약에 남은 갭이 새 계약 갭 목록에 없으면 알린다(이 checkout에 앞 계약이 있을 때만).
    const prev = [...after.slices.values()].filter((s) => s.ended).sort((a, b) => b.endSeq - a.endSeq)[0];
    const prevFile = prev && path.join(P.top, prev.path);
    if (prevFile && fs.existsSync(prevFile)) {
      const strip = (g) => oneLine(g.replace(/^\[[A-Z]+\]\s*/, ''));
      const mine = c.gaps.map(strip);
      const left = parseContract(fs.readFileSync(prevFile, 'utf8')).gaps.filter((g) => !mine.includes(strip(g)));
      if (left.length) process.stderr.write(`WARN 앞 조각 ${prev.id}의 남은 갭 ${left.length}건이 새 계약 갭 목록에 없다: ${left.map((g) => cut(g, 40)).join(' / ')}. LOW는 이 계약 갭 목록이나 정리 슬롯으로, UNREQ는 사용자에게 새 조각 후보로 보고한다.\n`);
    }
    return out(`조각 ${c.id} 시작: 예산 ${c.budget}세션, 시작 커밋 ${head.slice(0, 7)}, 계약 ${rel}(sha256 ${contract.slice(0, 8)}), 근거 입력 ${ref}.`);
  }
  out('사용법: plan slice start <계약 파일> --approval-ref <입력 ID> | switch <장치> <block|warn|off> --approval-ref <입력 ID> | close <ID> --approval-ref <입력 ID> | extend <ID> --by N --approval-ref <입력 ID> | carry <ID> --approval-ref <입력 ID> | status');
  return 1;
}

// ---------- CLI ----------
function parseArgs(argv) {
  const pos = [];
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const k = a.slice(2);
      const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
      flags[k] = v;
    } else pos.push(a);
  }
  return { pos, flags };
}
const readStdin = () => {
  try {
    return fs.readFileSync(0, 'utf8');
  } catch {
    return '';
  }
};
const nextId = (prefix, ids) => `${prefix}-${String(Math.max(0, ...[...ids].map((id) => +id.split('-')[1] || 0)) + 1).padStart(3, '0')}`;

// 입력 포착 명령. 프로젝트 훅과 사용자 범위 훅(--global)이 같이 부른다. 저장소는 훅 입력의 cwd(공식 필드)로 찾는다.
// --text 는 설치 세션처럼 훅 밖에서 받은 사용자 원문을 그대로 남길 때 쓴다(요약·의역 금지).
function captureCmd(flags, cwd, out) {
  const manual = typeof flags.text === 'string';
  const payload = manual ? JSON.stringify({ prompt: flags.text, origin: 'manual' }) : readStdin();
  let where = cwd;
  if (!manual) {
    try {
      const o = JSON.parse(payload || '{}');
      if (o && typeof o.cwd === 'string' && fs.existsSync(o.cwd) && fs.statSync(o.cwd).isDirectory()) where = o.cwd;
    } catch {}
  }
  let P;
  try {
    P = paths(where);
  } catch (e) {
    if (manual) throw e;
    const repo = orchestrationTarget(where); // 상위 폴더 세션이면 하네스 작업 원장으로(경로 정확 일치만)
    if (!repo) return 0; // 하네스 밖(git 아님)
    P = paths(repo);
  }
  if (!fs.existsSync(P.ledger)) {
    if (manual) throw new Error('공유 원장 없음. `plan init` 필요.');
    return 0; // 원장 없는 저장소에는 입력함을 만들지 않는다
  }
  if (flags.choice) {
    captureChoice(P, { tool: flags.tool ?? 'unknown', payload });
    return 0;
  }
  const rec = capture(P, { tool: flags.tool ?? 'unknown', payload });
  if (rec && flags.remind && (flags.format === 'claude' || flags.format === 'codex')) {
    const r = remind(where);
    if (r) out(JSON.stringify({ hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: r } }));
  }
  return 0;
}

// 기록이 원장·ref에 확정된 뒤의 캡슐 표시. 여기서 실패해도 기록 실패로 알리지 않는다(다시 시도해 중복 기록하지 않게).
function renderAfterWrite(P) {
  try {
    render(P);
  } catch (e) {
    process.stderr.write(`WARN 기록은 원장과 이력 ref에 확정됐다. 캡슐 표시만 실패했다: ${e.message}. \`plan render\`로 다시 만든다.\n`);
  }
}

export function main(argv, cwd = process.cwd()) {
  const { pos, flags } = parseArgs(argv);
  const [cmd, sub, arg] = pos;
  const out = (s) => {
    process.stdout.write(s.endsWith('\n') ? s : s + '\n');
    return 0;
  };
  const by = flags.quote ? 'user' : 'agent';
  if (cmd === 'inject') {
    // 훅 stdin(JSON)에서 시작 원인을 읽는다. Claude·Codex는 source, Grok은 camelCase 키를 쓴다.
    let event = flags.event ?? 'startup';
    if (flags['from-stdin']) {
      try {
        const o = JSON.parse(readStdin() || '{}');
        const name = String(o.hook_event_name ?? o.hookEventName ?? '');
        event = /compact/i.test(name) ? 'compact' : (o.source ?? o.trigger ?? event);
      } catch {}
    }
    const budget = flags['budget-chars'] !== undefined ? Math.max(0, Number(flags['budget-chars']) || 0) : typeof flags.budget === 'string' ? flags.budget : null;
    return out(inject(cwd, { event, format: flags.format ?? 'text', budget }));
  }
  if (cmd === 'capture') return captureCmd(flags, cwd, out);
  // 훅이 부르는 명령은 하네스 밖·원장 없는 저장소·미설치 브랜치에서 아무것도 하지 않는다(출력 없이 0, 디렉터리도 만들지 않음).
  const hook = cmd === 'guard' || cmd === 'stop-gate';
  let P;
  try {
    P = paths(cwd);
  } catch (e) {
    if (hook) return 0;
    throw e;
  }
  if (hook && (!fs.existsSync(P.ledger) || !installed(P))) return 0;
  // 쓰기 명령은 상태(다음 지시 번호 등)를 계산하기 전에 작업 원장을 확정 지점에 맞춘다.
  const writes = ['directive', 'order', 'revise', 'retrigger', 'adr', 'weekly-fail'].includes(cmd) || (cmd === 'triage' && !flags.list) || (cmd === 'slice' && sub !== 'status');
  if (writes && !(cmd === 'directive' && ['list', 'show'].includes(sub)) && healFromRef(P)) process.stderr.write('WARN 작업 원장이 이력 ref보다 뒤처져 있어(직전 기록의 파일 쓰기 실패) ref 기준으로 채웠다.\n');
  switch (cmd) {
    case 'init': {
      assertOwnLedger(P);
      fs.mkdirSync(P.inbox, { recursive: true });
      if (!fs.existsSync(P.ledger)) {
        // 이력 ref를 읽지 못하면(손상) 빈 원장으로 확정하지 않는다(refFile이 예외). ref는 있는데 원장 파일이 없으면 멈춘다.
        const fromRef = refFile(P, 'ledger.jsonl');
        if (fromRef === null && git(['rev-parse', '--verify', '-q', REF], P.top) !== null) throw new Error(`이력 ref(${REF})에 ledger.jsonl이 없다. 빈 원장으로 덮어쓰지 않는다. \`git log ${REF}\`로 확인한다.`);
        fs.writeFileSync(P.ledger, fromRef ?? '');
        if (!fromRef) snapshot(P, 'plan init');
      }
      fs.mkdirSync(path.join(P.top, '.plan'), { recursive: true });
      const cfg = path.join(P.top, '.plan', 'config.json');
      if (!fs.existsSync(cfg)) fs.writeFileSync(cfg, JSON.stringify({ version: 3, ledger: '<git-common-dir>/plan/ledger.jsonl', history_ref: REF }, null, 2) + '\n');
      const gi = path.join(P.top, '.gitignore');
      const cur = fs.existsSync(gi) ? fs.readFileSync(gi, 'utf8') : '';
      if (!cur.includes(CAPSULE_REL)) fs.appendFileSync(gi, `${cur && !cur.endsWith('\n') ? '\n' : ''}${CAPSULE_REL}\n`);
      const agentsFile = path.join(P.top, 'AGENTS.md');
      const agents = fs.existsSync(agentsFile) ? fs.readFileSync(agentsFile, 'utf8') : '';
      const next = withRules(agents);
      if (next !== agents) fs.writeFileSync(agentsFile, next);
      render(P);
      return out(`초기화 완료: 공유 원장 ${P.ledger}, 이력 ${REF}, AGENTS.md 규칙 블록, ${CAPSULE_REL}.`);
    }
    case 'restore': {
      // 잠금 안에서 원장과 adr·revisions 사본을 ref 기준으로 되돌린다. ref에 없는 파일은 지우지 않고 orphans/로 옮겨 보존한다.
      const moved = withLock(P, () => {
        const refLedger = refFile(P, 'ledger.jsonl');
        if (!refLedger) throw new Error('이력 ref가 없다.');
        fs.mkdirSync(P.dir, { recursive: true });
        fs.writeFileSync(P.ledger, refLedger);
        const stamp = new Date().toISOString().replace(/[:.]/g, '-');
        const aside = [];
        for (const sub of ['adr', 'revisions']) {
          const inRef = new Set((git(['ls-tree', '--name-only', `${REF}:${sub}`], P.top) ?? '').split('\n').filter(Boolean));
          for (const name of inRef) {
            const want = gitBuf(['show', `${REF}:${sub}/${name}`], P.top);
            const f = path.join(P.dir, sub, name);
            if (want && (!fs.existsSync(f) || !fs.readFileSync(f).equals(want))) {
              fs.mkdirSync(path.dirname(f), { recursive: true });
              fs.writeFileSync(f, want);
            }
          }
          const d = path.join(P.dir, sub);
          for (const name of fs.existsSync(d) ? fs.readdirSync(d) : []) {
            if (inRef.has(name) || !fs.statSync(path.join(d, name)).isFile()) continue;
            const to = path.join(P.dir, 'orphans', stamp, sub, name);
            fs.mkdirSync(path.dirname(to), { recursive: true });
            fs.renameSync(path.join(d, name), to);
            aside.push(`${sub}/${name}`);
          }
        }
        return aside;
      });
      renderAfterWrite(P);
      return out(`원장을 ${REF} 최신 스냅샷으로 복구했다.${moved.length ? ` 이력에 없는 스냅샷 ${moved.length}개는 ${path.join(P.dir, 'orphans')} 아래로 옮겨 보존했다: ${moved.join(', ')}` : ''}`);
    }
    case 'directive': {
      const { events } = readLedger(P);
      const state = fold(events);
      if (sub === 'list') {
        // 읽기 전용. 캡슐이 줄어도 원문·최신 변경·막힘을 여기서 본다(--all이면 종결 지시까지).
        const rows = state.order.map((id) => state.directives.get(id)).filter((d) => d && (flags.all || !TERMINAL.has(d.status)));
        return out(
          rows
            .map((d, i) => {
              const a = lastAmend(d);
              const parts = [`${i + 1}. ${d.id} ${d.status} 「${oneLine(d.text)}」`];
              if (a) parts.push(`   최신 변경#${d.amendments.length}(원장 #${a.seq}, ${a.backed ? '사용자 근거' : `근거 없음: ${a.source}`}): 「${oneLine(a.text)}」`);
              if (d.status === 'BLOCKED') parts.push(`   막힘: ${oneLine(d.blocker)} / 해제 조건: ${oneLine(d.unblock)}`);
              if (d.next) parts.push(`   다음: ${oneLine(d.next)}`);
              if (d.evidence) parts.push(`   증거: ${oneLine(d.evidence)}`);
              return parts.join('\n');
            })
            .join('\n') || '(열린 지시 없음)',
        );
      }
      if (sub === 'show') {
        const d = state.directives.get(arg);
        if (!d) throw new Error(`원장에 없는 지시 ${arg}.`);
        const lines = [`${d.id} ${d.status} (원장 #${d.seq}, ${d.ts}, 출처 ${d.source})`, `원문: ${d.text}`];
        d.amendments.forEach((a, i) => lines.push(`변경#${i + 1} (원장 #${a.seq}, ${a.backed ? '사용자 근거' : '근거 없음'}, 출처 ${a.source}): ${a.text}`));
        for (const e of events.filter((e) => e.type === 'directive.status' && e.id === d.id))
          lines.push(`상태 #${e.seq} ${e.ts} → ${e.status}${e.blocker ? ` 막힘:${e.blocker}` : ''}${e.unblock ? ` 해제:${e.unblock}` : ''}${e.evidence ? ` 증거:${e.evidence}` : ''}${e.quote ? ` 인용:「${e.quote}」` : ''}`);
        return out(lines.join('\n'));
      }
      if (sub === 'add') {
        let text = flags.text;
        let source = flags.source;
        if (flags['from-inbox']) {
          const rec = listInbox(P).find((x) => x.id === flags['from-inbox']);
          if (!rec) throw new Error(`inbox ${flags['from-inbox']} 없음.`);
          text = rec.prompt;
          source = `inbox:${rec.id}:${rec.tool}:${rec.ts}`;
        }
        const id = nextId('DIR', state.directives.keys());
        appendEvent(P, { type: 'directive.add', id, text, source, by: 'user' });
        if (flags['from-inbox']) appendEvent(P, { type: 'inbox.triage', refs: withDups(P, [flags['from-inbox']]), as: id });
        renderAfterWrite(P);
        return out(id);
      }
      if (sub === 'amend') {
        // 변경도 사용자 근거가 있어야 사용자 변경이다(--quote 또는 --from-inbox). 근거가 없으면 에이전트 기록으로 남는다.
        let text = flags.text;
        let source = flags.source;
        let quote = flags.quote;
        let approval_ref = flags['approval-ref'];
        if (flags['from-inbox']) {
          const rec = listInbox(P).find((x) => x.id === flags['from-inbox']);
          if (!rec) throw new Error(`inbox ${flags['from-inbox']} 없음.`);
          text ??= rec.prompt;
          source = `inbox:${rec.id}:${rec.tool}:${rec.ts}`;
          if (classifyRecord(rec) === 'user') {
            quote = rec.prompt;
            approval_ref = rec.id;
          }
        }
        appendEvent(P, { type: 'directive.amend', id: arg, text, source, by: quote ? 'user' : 'agent', quote, approval_ref });
        renderAfterWrite(P);
        return out(`${arg} 변경 기록.`);
      }
      if (sub === 'set') {
        const ev = { type: 'directive.status', id: arg, status: flags.status, by, quote: flags.quote, approval_ref: flags['approval-ref'] };
        for (const k of ['evidence', 'blocker', 'unblock', 'work', 'next', 'superseded_by']) if (flags[k]) ev[k] = flags[k];
        consumeQuote(P, appendEvent(P, ev));
        renderAfterWrite(P);
        return out(`${arg} → ${flags.status}.`);
      }
      break;
    }
    case 'order':
      consumeQuote(P, appendEvent(P, { type: 'order.set', order: String(flags.ids).split(','), by, quote: flags.quote, approval_ref: flags['approval-ref'] }));
      renderAfterWrite(P);
      return out('순서 기록.');
    case 'revise': {
      const state = fold(readLedger(P).events);
      const file = String(flags.file);
      const buf = fs.readFileSync(path.join(P.top, file));
      const rev = state.plan ? state.plan.rev + 1 : Number(flags.rev ?? 1);
      const snap = `revisions/REV-${String(rev).padStart(3, '0')}.md`;
      const body = buf.toString('utf8');
      const carry = body.match(/<!-- ADR-BASIS:carry-forward REV-(\d+) sha256:([0-9a-f]{64}) -->/);
      if (carry && (!state.plan || Number(carry[1]) !== state.plan.rev || carry[2] !== state.plan.sha256)) throw new Error('ADR 기준점 계승은 직전 승인 REV 번호·sha256과 같아야 한다.');
      const adr_basis = [];
      for (const a of state.adrs.values()) {
        if (a.status !== 'accepted') continue;
        const prior = state.plan?.adr_basis?.find((b) => b.id === a.id && b.accepted_seq === a.acceptedSeq);
        const legacy = !state.plan?.adr_basis && state.plans.some((p) => p.seq > (a.acceptedSeq ?? 0) && p.triggers?.includes(a.id));
        if (!mentions(body, a.id) && !(carry && (prior || legacy))) continue;
        const adrSnap = readSnap(P, a.snapshot);
        if (!adrSnap) throw new Error(`${a.id} ADR 기준점 스냅샷 없음.`);
        adr_basis.push({ id: a.id, accepted_seq: a.acceptedSeq, sha256: sha256(adrSnap) });
      }
      // 핵심 항목 지연 경보: 직전 승인본보다 뒤로 밀린 핵심 항목마다 --ack-core-delay와 정해진 문구의 사용자 입력이 필요하다.
      const delayEvents = [];
      const core = coreItems(P);
      const prevBody = state.plan ? readSnap(P, state.plan.snapshot)?.toString('utf8') : null;
      const delayMode = sliceState(P, readLedger(P).events).switches['core-delay'];
      if (core.length && prevBody != null && delayMode !== 'off') {
        const delays = coreDelays(prevBody, body, core);
        if (delays === null) process.stderr.write('WARN 직전 승인 계획 또는 새 계획에 순서 블록 <!-- PLAN-ORDER: … -->이 없어 핵심 항목 지연을 판정하지 않았다.\n');
        else if (delays.length) {
          const acks = String(flags['ack-core-delay'] === true ? '' : (flags['ack-core-delay'] ?? '')).split(',').map((x) => x.trim()).filter(Boolean);
          const refs = String(flags['delay-approval-ref'] === true ? '' : (flags['delay-approval-ref'] ?? '')).split(',').map((x) => x.trim()).filter(Boolean);
          const list = delays.map(delayLabel).join(', ');
          const unacked = delays.some((x) => !acks.includes(delayTag(x)));
          if (unacked && delayMode === 'warn') process.stderr.write(`WARN 핵심 항목이 뒤로 밀린다: ${list}(스위치 core-delay=warn이라 막지 않는다). 사용자에게 밀리는 칸 수와 함께 보고한다.\n`);
          else {
            if (unacked)
              throw new Error(`핵심 항목이 뒤로 밀린다: ${list}. 사용자에게 밀리는 칸 수와 함께 보고하고(막힘 증거가 없으면 지연안에 (권장)을 붙이지 않는다), 사용자가 ${delays.map((x) => `「${delayPhrase(x)}」`).join(', ')}를 입력한 뒤 \`--ack-core-delay "${delays.map(delayTag).join(',')}" --delay-approval-ref <입력 ID,…>\`로 등록한다.`);
            if (refs.length !== delays.length) throw new Error(`--delay-approval-ref에 밀린 항목(${delays.map(delayTag).join(',')})마다 근거 입력 ID를 같은 순서로 준다(${delays.length}개).`);
            const consumed = fold(readLedger(P).events).triaged;
            if (new Set(refs).size !== refs.length) throw new Error('근거 입력 하나를 여러 지연 승인에 쓰지 않는다(1회 사용).');
            delays.forEach((x, i) => {
              const rec = listInbox(P).find((r) => r.id === refs[i]);
              const why = rec ? approvalProblem(rec, delayPhrase(x), { consumed }) : `근거 입력 ${refs[i]}가 입력함에 없다`;
              if (why) throw new Error(`${why}.`);
              delayEvents.push({ type: 'inbox.triage', refs: withDups(P, [refs[i]]), as: `delay:REV-${rev}:${delayTag(x)}` });
            });
          }
        }
      }
      const ev = appendEvent(
        P,
        {
          type: 'plan.revise',
          rev,
          file,
          snapshot: snap,
          sha256: sha256(buf),
          reason: flags.baseline ? 'BASELINE' : flags.reason,
          triggers: String(flags.triggers ?? '').split(',').filter(Boolean),
          by,
          quote: flags.quote,
          approval_ref: flags['approval-ref'],
          adr_basis,
          ...(core.length ? { core: { items: core, mode: delayMode } } : {}), // 지연 판정 기준(읽을 때 이 값으로 다시 본다)
        },
        [{ rel: snap, buf }],
        null,
        delayEvents,
      );
      consumeQuote(P, ev);
      renderAfterWrite(P);
      return out(`REV-${rev} 등록(스냅샷 ${snap}).`);
    }
    case 'retrigger': {
      const rev = Number(flags.rev);
      const triggers = String(flags.triggers ?? '').split(',').filter(Boolean);
      const ev = appendEvent(P, { type: 'plan.retrigger', rev, triggers, reason: flags.reason, by, quote: flags.quote, approval_ref: flags['approval-ref'] });
      consumeQuote(P, ev);
      renderAfterWrite(P);
      return out(`REV-${rev} 트리거 정정: ${triggers.join(',')} (#${ev.seq}).`);
    }
    case 'adr': {
      const state = fold(readLedger(P).events);
      const snapOf = (id, text) => [{ rel: `adr/${id}.md`, buf: Buffer.from(text) }];
      if (sub === 'accept' || sub === 'propose') {
        const status = sub === 'accept' ? 'accepted' : 'proposed';
        const file = flags.file ?? state.adrs.get(arg)?.file;
        const f = path.join(P.top, file);
        const before = fs.readFileSync(f, 'utf8');
        const previous = state.adrs.get(arg);
        if (status === 'accepted' && previous?.status === 'accepted' && readSnap(P, previous.snapshot)?.equals(Buffer.from(before))) return out(`${arg} accepted(같은 확정본, 변경 없음).`);
        const after = setAdrFileStatus(f, status);
        try {
          appendEvent(P, { type: 'adr.status', id: arg, status, file, by, quote: flags.quote, approval_ref: flags['approval-ref'] }, snapOf(arg, after));
        } catch (e) {
          if (after !== before) fs.writeFileSync(f, before); // 원장 기록이 거부되면 파일도 되돌린다.
          throw e;
        }
        renderAfterWrite(P);
        return out(`${arg} ${status}.`);
      }
      if (sub === 'supersede') {
        const old = state.adrs.get(arg);
        if (!old) throw new Error(`원장에 없는 ADR ${arg}.`);
        const f = path.join(P.top, old.file);
        const has = fs.existsSync(f);
        const before = has ? fs.readFileSync(f, 'utf8') : null;
        const after = has ? setAdrFileStatus(f, 'superseded', `by ${flags.by}`) : null;
        try {
          appendEvent(P, { type: 'adr.status', id: arg, status: 'superseded', superseded_by: flags.by, by, quote: flags.quote, approval_ref: flags['approval-ref'] }, has ? snapOf(arg, after) : []);
        } catch (e) {
          if (has && after !== before) fs.writeFileSync(f, before);
          throw e;
        }
        renderAfterWrite(P);
        return out(`${arg} superseded by ${flags.by}.${has ? '' : ' (현재 브랜치에 파일이 없어 파일 상태는 병합 때 갱신)'}`);
      }
      if (sub === 'import') {
        // 기존 ADR 폴더를 원장으로 이관. 파일 상태 줄을 그대로 읽고 파일은 바꾸지 않는다. 번호 충돌은 멈추고 보고한다.
        const dir = path.join(P.top, String(arg ?? 'docs/adr'));
        const ref = typeof flags.ref === 'string' ? flags.ref : null; // 다른 브랜치에만 있는 ADR을 체크아웃 없이 이관
        const relDir = path.relative(P.top, dir).split(path.sep).join('/');
        // 바이트를 그대로 읽는다(git()의 trimEnd가 끝 줄바꿈을 지우던 결함 수정).
        const readAdr = (f) => (ref ? gitBuf(['show', `${ref}:${relDir}/${f}`], P.top) ?? Buffer.alloc(0) : fs.readFileSync(path.join(dir, f)));
        const files = (ref ? (git(['ls-tree', '--name-only', `${ref}:${relDir}`], P.top) ?? '').split('\n').filter(Boolean) : fs.readdirSync(dir)).filter((f) => /\.md$/i.test(f)).sort();
        const found = new Map();
        const problems = [];
        const unnumbered = [];
        for (const f of files) {
          if (/template|^index\.md$|^readme\.md$/i.test(f)) continue; // 양식·색인·안내 문서는 결정이 아니다
          const m = /^\d{4}-\d{2}-\d{2}/.test(f) ? null : f.match(/^(?:ADR-?)?(\d{3,4})(?=[-_.])/i);
          if (!m) {
            unnumbered.push(f);
            continue;
          }
          const id = `ADR-${m[1]}`;
          if (found.has(id)) problems.push(`번호 충돌 ${id}: ${found.get(id)} / ${f}`);
          found.set(id, f);
        }
        // 새 프로토콜이 시작된 뒤에는 이관이 결정을 확정하지 않는다(proposed만). 원장에 아직 없는 ID를 기록 전에 모두 검사해 이 차단으로 인한 부분 기록을 막는다.
        if (readLedger(P).events.some((e) => e.schema >= 3 && e.source !== 'migration'))
          for (const [id, f] of found) {
            if (state.adrs.has(id)) continue;
            const st = adrFileStatus(readAdr(f).toString('utf8'));
            if (!st || st === 'proposed') continue;
            const next = st === 'accepted' ? `사용자 원문으로 \`adr accept ${id} --file <경로> --quote "<원문>"\`을 먼저 기록한 뒤 다시 이관한다` : '기각·폐기·대체는 사용자 결정이다(기각 기록 명령은 아직 없다). 사용자 원문으로 결정을 기록한다';
            problems.push(`${id}(${f}) 파일 상태 ${st}: 새 프로토콜 시작 뒤 이관은 proposed만 기록한다. ${next}.`);
          }
        if (problems.length) throw new Error(`ADR 이관 중단(사용자 결정 필요):\n${problems.join('\n')}`);
        const rel = (f) => path.relative(P.top, path.join(dir, f)).split(path.sep).join('/');
        const later = [];
        const report = [];
        for (const [id, f] of found) {
          if (state.adrs.has(id)) continue;
          const buf = readAdr(f);
          const text = buf.toString('utf8');
          const st = adrFileStatus(text);
          if (st === 'superseded') {
            const by2 = (text.match(STATUS_LINE)?.[3] ?? '').match(/ADR-?(\d{3,4})/i);
            later.push({ id, f, text, buf, by: by2 ? `ADR-${by2[1]}` : null });
            continue;
          }
          const status = st ?? 'proposed';
          appendEvent(P, { type: 'adr.status', id, status, file: rel(f), by: 'agent', source: 'migration', note: `${st ? 'import' : 'import: 상태 표기 인식 불가'}${ref ? ` (브랜치 ${ref}에만 있음)` : ''}` }, snapOf(id, buf));
          report.push(`${id} ${status}${ref ? ` [${ref}]` : ''}${st ? '' : ` (상태 표기 인식 불가: 「${adrStatusRaw(text) || '상태 줄 없음'}」 → 사용자 확인 필요)`}`);
        }
        for (const x of later) {
          const cur = fold(readLedger(P).events).adrs.get(x.by);
          if (x.by && cur?.status === 'accepted') {
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'accepted', file: rel(x.f), by: 'agent', source: 'migration', note: 'import' }, snapOf(x.id, x.buf));
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'superseded', superseded_by: x.by, by: 'agent', source: 'migration', note: 'import' });
            report.push(`${x.id} superseded by ${x.by}`);
          } else {
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'deprecated', file: rel(x.f), by: 'agent', source: 'migration', note: 'import: 대체 ADR 불명' }, snapOf(x.id, x.buf));
            report.push(`${x.id} 대체됨 표기지만 대체 ADR을 찾지 못함 → 사용자 확인 필요(원장에는 deprecated, 파일 상태와 불일치 오류로 표시됨)`);
          }
        }
        renderAfterWrite(P);
        for (const f of unnumbered) report.push(`번호 없는 결정 문서 ${f} → 이관하지 않음. 사용자와 ADR 번호를 정한 뒤 파일명을 바꿔 다시 import한다.`);
        return out(report.join('\n') || '(새로 이관할 ADR 없음)');
      }
      if (sub === 'impact') {
        consumeQuote(P, appendEvent(P, { type: 'adr.impact', id: arg, impact: 'none', reason: flags.reason, by, quote: flags.quote, approval_ref: flags['approval-ref'] }));
        renderAfterWrite(P);
        return out(`${arg} 계획 영향 없음 기록(${by}).`);
      }
      break;
    }
    case 'precommit': {
      // git pre-commit 공통 진입점: 커밋되는 작업트리를 검사한다(미분류 입력·ADR 미반영은 세션 종료 게이트 몫).
      const { errors, warns } = check(P);
      const ss = sliceState(P, readLedger(P).events);
      if (budgetHit(ss) && ss.switches.budget === 'block') {
        const msg = exhaustedMsg(ss.active, ss.usage);
        const i = warns.indexOf(msg);
        if (i >= 0) warns.splice(i, 1); // 같은 문구를 WARN·ERROR로 두 번 보이지 않는다
        errors.push(msg);
      }
      for (const w of warns) process.stderr.write(`WARN ${w}\n`);
      for (const e of errors) process.stderr.write(`ERROR ${e}\n`);
      return errors.length ? 1 : 0;
    }
    case 'triage': {
      // 조각·주간 FAIL 승인 기록은 전용 명령만 쓴다(as 무검사 triage로 승인을 꾸미지 못하게, ADR-0005 3-0).
      const asName = String(flags['rest-as'] ?? flags.as ?? '');
      if (!flags.list && RESERVED_TRIAGE.test(asName)) throw new Error(`분류 이름 「${cut(asName, 40)}」: slice:·weekly-fail:·delay: 접두어는 \`plan slice …\`·\`plan weekly-fail close\`·\`plan revise --ack-core-delay\` 명령만 쓴다(승인 기록 위조 차단).`);
      const state = fold(readLedger(P).events);
      const rows = listInbox(P).filter((x) => !state.triaged.has(x.id));
      if (flags.list) return out(rows.map((r) => `${r.id} ${r.ts} ${r.tool}${classifyRecord(r) !== 'user' ? ` [출처 ${classifyRecord(r)}]` : ''}${r.kind === 'choice' ? ' [선택지 응답]' : ''}${DIRECTIVE_LIKE.test(r.prompt) ? ' [지시형]' : ''}${r.dups?.length ? ` [중복 ${r.dups.join(',')} 함께 분류]` : ''}${r.conflict_of ? ` [같은 키 다른 본문: ${r.conflict_of}]` : ''}${r.origin_note ? ` [${r.origin_note}]` : ''} 「${cut(r.prompt, 80)}」`).join('\n') || '(미분류 없음)');
      if (flags['rest-as']) {
        // 나머지 일괄 분류. 지시형 문장은 일괄로 버릴 수 없다(하나씩 판단).
        // 제시된 선택지와 정확히 같은 선택지 응답은 지시형 문구여도 일괄 분류할 수 있다(자유 입력은 한 건씩).
        const risky = rows.filter((r) => DIRECTIVE_LIKE.test(r.prompt) && !(r.kind === 'choice' && r.choice_label));
        if (risky.length) throw new Error(`지시형 입력 ${risky.length}건은 일괄 분류할 수 없다: ${risky.map((r) => r.id).join(', ')}`);
        if (!rows.length) return out('(미분류 없음)');
        appendEvent(P, { type: 'inbox.triage', refs: withDups(P, rows.map((r) => r.id)), as: String(flags['rest-as']) });
        return out(`${rows.length}건 → ${flags['rest-as']}.`);
      }
      appendEvent(P, { type: 'inbox.triage', refs: withDups(P, [sub]), as: flags.as });
      return out(`${sub} → ${flags.as}.`);
    }
    case 'slice':
      return sliceCmd(P, cwd, sub, arg, flags, out, pos[3]);
    case 'weekly-fail': {
      // 주간 FAIL 닫기(방법론 5-2): 문구가 정확히 「<key> <고침|이월|영향없음>」인 사용자 입력으로만, 최신 보고서의 FAIL에 대해서만.
      const key = arg;
      const decision = pos[3];
      const ref = flags['approval-ref'];
      if (sub !== 'close' || !/^wf-[0-9a-f]{8}$/.test(key ?? '') || !WEEKLY_DECISIONS.includes(decision) || typeof ref !== 'string')
        throw new Error(`사용법: plan weekly-fail close <wf-key> <${WEEKLY_DECISIONS.join('|')}> --approval-ref <입력 ID>`);
      const w = latestWeeklyFails(P);
      if (!w?.fails.some((x) => x.key === key)) throw new Error(`${key}는 최신 주간 보고서 FAIL에 없다${w ? `(보고서 ${w.report})` : '(주간 보고서 없음)'}.`);
      const phrase = `${key} ${decision}`;
      const rec = listInbox(P).find((r) => r.id === ref);
      if (!rec) throw new Error(`근거 입력 ${ref}가 입력함에 없다.`);
      appendEvent(P, { type: 'inbox.triage', refs: withDups(P, [ref]), as: `weekly-fail:${key}:${decision}:report=${w.report}` }, [], (events) => {
        const st = weeklyCloseState(P, events);
        if (st.closed.has(`${w.report}|${key}`)) throw new Error(`${key}는 보고서 ${w.report}에 대해 이미 닫혔다.`);
        const why = approvalProblem(rec, phrase, { consumed: fold(events).triaged });
        if (why) throw new Error(`${why}. 사용자가 AI 도구 입력창에 「${phrase}」를 그대로 입력한 기록만 근거가 된다.`);
      });
      return out(`주간 FAIL ${key} → ${decision}(보고서 ${w.report}), 근거 입력 ${ref}.`);
    }
    case 'render':
      render(P);
      return out(`${CAPSULE_REL} 갱신.`);
    case 'check': {
      const { errors, warns } = check(P, { close: !!flags.close });
      if (flags.json) {
        out(JSON.stringify({ schema: 1, errors, warns }));
        return errors.length ? 1 : 0;
      }
      for (const w of warns) out(`WARN ${w}`);
      for (const e of errors) out(`ERROR ${e}`);
      if (!errors.length) out(`OK plan check${flags.close ? ' --close' : ''}`);
      return errors.length ? 1 : 0;
    }
    case 'stop-gate': {
      // 턴 종료 게이트: 원장 무결성·진입 문서 오류만 막는다. 낡은 캡슐 사본은 조용히 갱신한다. 재차단 루프 방지.
      let o = {};
      try {
        o = JSON.parse(readStdin() || '{}');
      } catch {}
      if (o.stop_hook_active || o.stopHookActive) return 0;
      if (!fs.existsSync(P.ledger)) return 0;
      try {
        render(P);
      } catch {}
      const { errors } = check(P);
      if (errors.length) out(JSON.stringify({ decision: 'block', reason: `[plan] 계획 정본 검사 실패 — 고친 뒤 끝낸다:\n${errors.slice(0, 5).join('\n')}` }));
      return 0;
    }
    case 'guard': {
      const msg = guard(cwd, readStdin());
      if (msg) {
        process.stderr.write(msg + '\n');
        return 2;
      }
      return 0;
    }
    case 'metrics':
      return out(JSON.stringify(metrics(P), null, 2));
    default:
      out('사용법: plan init|restore|directive add|amend|set|list|show|order|revise|retrigger|adr accept|propose|supersede|import|impact|triage|slice start|switch|close|extend|carry|status|weekly-fail close|render|check [--close]|inject|capture|guard|stop-gate|precommit|metrics');
      return cmd ? 1 : 0;
  }
  out(`알 수 없는 하위 명령: ${cmd} ${sub ?? ''}`);
  return 1;
}

if (process.argv[1]?.endsWith('plan.mjs')) {
  try {
    process.exitCode = main(process.argv.slice(2)) ?? 0;
  } catch (e) {
    process.stderr.write(`plan: ${e.message}\n`);
    process.exitCode = 1;
  }
}
