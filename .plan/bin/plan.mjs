export function bloatNote(P, ss) {
  const s = ss.active;
  if (!s || ss.switches.bloat === 'off') return null;
  let cfg = {};
  try {
    cfg = JSON.parse(fs.readFileSync(path.join(P.top, '.plan', 'config.json'), 'utf8'))?.energy?.bloat ?? {};
  } catch {}
  const ratio = Number(cfg.ratio ?? 0.6);
  const need = Number(cfg.sessions ?? 2);
  if (spawnSync('git', ['merge-base', '--is-ancestor', s.commit, 'HEAD'], { cwd: P.top, stdio: 'ignore' }).status !== 0) return null;
  const log = git(['-c', 'core.quotePath=false', 'log', '--reverse', '--numstat', '--no-renames', '--format=@%cI', `${s.commit}..HEAD`], P.top);
  if (!log) return null;
  const classes = energyClasses(P);
  const inputs = listInbox(P).filter(countable).map((r) => ({ t: Math.floor(Date.parse(r.ts) / 1000) * 1000, key: sessionKey(r) })).sort((x, y) => x.t - y.t);
  const sessions = new Map(); // 처음 나온 순서를 지킨다
  let cur = null;
  for (const line of log.split('\n')) {
    if (line.startsWith('@')) {
      const t = Date.parse(line.slice(1));
      const before = inputs.filter((x) => x.t <= t).at(-1);
      const key = before?.key ?? `date|${seoulDate(line.slice(1))}`;
      if (!sessions.has(key)) sessions.set(key, { aux: 0, all: 0 });
      cur = sessions.get(key);
      continue;
    }
    const m = line.match(/^(\d+|-)\t(\d+|-)\t(.+)$/);
    if (!m || !cur) continue;
    const n = (m[1] === '-' ? 0 : Number(m[1])) + (m[2] === '-' ? 0 : Number(m[2]));
    cur.all += n;
    if (['evidence', 'session', 'script'].includes(classOf(classes, m[3]))) cur.aux += n;
  }
  const recent = [...sessions.values()].filter((d) => d.all > 0).slice(-need);
  if (recent.length < need || !recent.every((d) => d.aux / d.all > ratio)) return null;
  const pct = recent.map((d) => `${Math.round((d.aux / d.all) * 100)}%`).join('·');
  return `[plan] 조각 ${s.id} 보조물 비중 ${pct}(최근 ${need}세션)이 ${Math.round(ratio * 100)}%를 넘었다 — 사용자에게 「계속 / 갭 분리 / 범위 축소」를 묻는다.`;
}
