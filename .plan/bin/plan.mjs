// 읽을 때 쓰는 출처 분류. 저장된 기록은 바꾸지 않고, 결과는 저장된 출처보다 높아지지 않는다(낮추기만).
// 등급 user > legacy > unknown·manual > agent. 반환: user|legacy|unknown|manual|agent.
const ORIGIN_RANK = { user: 4, legacy: 3, unknown: 2, manual: 2, agent: 1 };
const FRAME_NAMES = 'cross-session-message|agent-message|task-notification|system-reminder';
export function classifyRecord(rec) {
  const text = String(rec?.prompt ?? '');
  const head = text.trimStart();
  const given = rec?.origin === undefined || rec?.origin === null ? 'legacy' : rec.origin;
  const stored = Object.hasOwn(ORIGIN_RANK, given) ? given : 'unknown';
  let cap = stored;
  if (new RegExp(`^<(?:${FRAME_NAMES})(?:\\s|>)`, 'i').test(head)) cap = 'agent';
  else if (/^<[A-Za-z_][\w.:-]*(?=[\s>/]|$)/.test(head) && !/^<pasted_content(?=[\s>/]|$)/i.test(head)) cap = 'unknown';
  else if (new RegExp(`<(?:${FRAME_NAMES})(?:\\s|>)`, 'i').test(text)) cap = 'unknown';
  let out = ORIGIN_RANK[cap] < ORIGIN_RANK[stored] ? cap : stored;
  if (rec?.pair_origin && ORIGIN_RANK[rec.pair_origin] < ORIGIN_RANK[out]) out = rec.pair_origin;
  return out;
}
// 에이전트·세션 간 메시지(effective agent)와 다른 기록의 중복(dup_of)을 뺀 사용자 후보 입력.
export const listInbox = (P) => listInboxAll(P).filter((r) => !r.dup_of && classifyRecord(r) !== 'agent');
// 키 없는 옛 포착 기록과 키 있는 새 기록이 같은 입력이면 읽을 때 1대1로 묶는다(저장 파일은 바꾸지 않는다).
// 같은 도구·세션·본문, 30초 이내. 묶음의 출처는 둘 중 낮은 쪽(옛 사본의 user 기록이 승인 후보로 남지 않게).
const DUP_WINDOW_MS = 30000;
export function pairDuplicates(recs) {
  const used = new Set();
  const keyed = recs.filter((r) => r.key && !r.conflict_of);
  for (const r of recs) {
    if (r.key || r.conflict_of) continue;
    const text = oneLine(r.prompt);
    const k = keyed.find((k) => !used.has(k) && k.tool === r.tool && k.session && k.session === r.session && oneLine(k.prompt) === text && Math.abs(Date.parse(k.ts) - Date.parse(r.ts)) <= DUP_WINDOW_MS);
    if (!k) continue;
    used.add(k);
    r.dup_of = k.id;
    k.dups = [r.id];
    const low = [k, r].map((x) => classifyRecord(x)).sort((a, b) => ORIGIN_RANK[a] - ORIGIN_RANK[b])[0];
    k.pair_origin = low;
  }
  return recs;
}
// 분류 기록에 넣을 입력 ID: 묶인 중복 기록도 함께 넣는다(옛 판 CLI가 그 기록을 미분류로 세지 않게).
export function withDups(P, ids) {
  const all = listInboxAll(P);
  const out = new Set(ids);
  for (const id of ids) for (const d of all.find((r) => r.id === id)?.dups ?? []) out.add(d);
  return [...out];
}
// 저장된 기록 전체(경고 집계·승인 증거 대조용). 깨진 줄은 버리지 않고 corrupt에 파일:줄로 모은다(check가 알린다).
export function listInboxAll(P, corrupt = null) {
  if (!fs.existsSync(P.inbox)) return [];
  const recs = fs
    .readdirSync(P.inbox)
    .filter((f) => f.endsWith('.jsonl'))
    .sort()
    .flatMap((f) =>
      fs
        .readFileSync(path.join(P.inbox, f), 'utf8')
        .split('\n')
        .map((l, i) => {
          if (!l.trim()) return null;
          try {
            const r = JSON.parse(l);
            if (r && typeof r === 'object' && !Array.isArray(r)) return r;
          } catch {}
          corrupt?.push(`${f}:${i + 1}`);
          return null;
        })
        .filter(Boolean),
    );
  return pairDuplicates(recs);
}
const syntheticPrompt = (prompt) => new RegExp(`<(?:${FRAME_NAMES})(?:\\s|>)`, 'i').test(String(prompt));
export function capture(P, { tool, payload }) {
  let obj = {};
  try {
    obj = JSON.parse(payload || '{}');
  } catch {
    obj = { prompt: payload };
  }
  if (!obj || typeof obj !== 'object' || Array.isArray(obj)) obj = {}; // null·문자열·배열 JSON은 포착할 입력이 없다(null이면 TypeError로 죽던 것 방지)
  const prompt = obj.prompt ?? obj.user_prompt ?? obj.message ?? obj.input ?? '';
  if (!String(prompt).trim()) return null;
  const ts = new Date().toISOString();
  // 맨 앞이 하네스 프레임일 때만 합성(agent)으로 저장한다. 본문 중간 프레임은 아래에서 unknown으로 낮춘다(사용자 지시가 게이트에서 사라지지 않게).
  const leadingFrame = new RegExp(`^<(?:${FRAME_NAMES})(?:\\s|>)`, 'i').test(String(prompt).trimStart());
  const synthetic = obj.role === 'assistant' || obj.parent_session_id || obj.synthetic || obj.ignored || leadingFrame;
  const nativePrompt = ['claude', 'codex', 'grok'].includes(tool) && (obj.hook_event_name ?? obj.hookEventName) === 'UserPromptSubmit' && (obj.session_id ?? obj.sessionId);
  // 출처는 낮추기만 한다. payload의 origin:'user' 자기 신고는 user로 올리지 못한다.
  const openCodeUser = tool === 'opencode' && obj.origin === 'user' && (obj.session_id ?? obj.sessionId) && (obj.message_id ?? obj.messageId) && !obj.parent_session_id;
  let origin = synthetic ? 'agent' : ['agent', 'unknown', 'manual'].includes(obj.origin) ? obj.origin : nativePrompt || openCodeUser ? 'user' : 'unknown';
  if (origin === 'user' && syntheticPrompt(prompt)) origin = 'unknown'; // 본문 중간 프레임: 승인 근거 불가, 미분류 게이트에는 남긴다
  const session = obj.session_id ?? obj.sessionId ?? null;
  const rec = { id: sha256(ts + prompt).slice(0, 12), ts, tool, session, cwd: obj.cwd ?? P.top, origin, message: obj.message_id ?? null, parent_session: obj.parent_session_id ?? null, prompt };
  // Codex 비대화형(`codex exec`) 세션의 입력은 사람이 친 것이 아니다. 기록 첫 줄 session_meta로 판정하고, 못 읽으면 출처를 바꾸지 않고 표시만 한다.
  if (tool === 'codex' && obj.transcript_path) {
    const kind = codexSessionKind(obj.transcript_path);
    if (kind === 'exec') Object.assign(rec, { origin: 'agent', origin_reason: 'codex_exec' });
    else if (kind !== 'interactive') rec.origin_note = '출처 판정 불가(transcript)';
  }
  const turn = obj.prompt_id ?? obj.promptId ?? obj.turn_id ?? obj.turnId ?? null;
  return persistRecord(P, rec, session && turn ? `${tool}:${session}:${turn}` : null);
}

// 입력함에 한 건을 남긴다. 같은 입력을 여러 훅(프로젝트·사용자 범위)이 포착해도 키(Claude prompt_id, Codex turn_id 등)로 한 건만 남긴다.
// 원장 잠금 대신 키 표식 파일을 선점한다(포착이 원장 잠금 대기로 실패해 입력을 잃지 않게). 같은 키·다른 본문은 버리지 않는다.
function persistRecord(P, rec, key) {
  assertOwnLedger(P);
  fs.mkdirSync(P.inbox, { recursive: true });
  let claimed = null;
  if (key) {
    const h = sha256(key);
    rec.key = key;
    rec.id = h.slice(0, 12);
    const keys = path.join(P.inbox, '.keys');
    const marker = path.join(keys, h.slice(0, 32));
    const promptSha = sha256(String(rec.prompt));
    try {
      fs.mkdirSync(keys, { recursive: true });
      const fd = fs.openSync(marker, 'wx');
      try {
        fs.writeSync(fd, JSON.stringify({ id: rec.id, prompt_sha: promptSha }));
      } finally {
        fs.closeSync(fd);
      }
      claimed = marker;
    } catch (e) {
      if (e.code === 'EEXIST') {
        let prev = {};
        for (let i = 0; i < 5 && !prev.prompt_sha; i++) {
          try {
            prev = JSON.parse(fs.readFileSync(marker, 'utf8'));
          } catch {
            Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 20);
          }
        }
        if (prev.prompt_sha === promptSha) {
          // 표식만 있고 기록이 없으면(선점한 쪽이 저장 전에 실패·종료) 이번에 남긴다. 잠깐 기다려 동시 저장을 기다린다.
          for (let i = 0; i < 3; i++) {
            if (inboxHas(P, prev.id ?? rec.id)) return null; // 다른 훅이 이미 같은 입력을 남겼다
            Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 30);
          }
        } else {
          rec.conflict_of = prev.id ?? rec.id; // 같은 키·다른 본문(또는 확인 불가): 원문을 보존한다
          rec.id = sha256(key + rec.ts + rec.prompt).slice(0, 12);
        }
      } // 그 밖의 표식 실패는 키 없이 그냥 쓴다(유실보다 중복이 낫다)
    }
  }
  const file = path.join(P.inbox, `${rec.ts.slice(0, 7)}.jsonl`);
  try {
    // 앞선 부분 저장으로 줄이 끊겨 있으면 새 줄에서 시작한다(깨진 줄에 이어 붙이지 않는다).
    let lead = '';
    try {
      const st = fs.statSync(file);
      if (st.size) {
        const fd = fs.openSync(file, 'r');
        const b = Buffer.alloc(1);
        fs.readSync(fd, b, 0, 1, st.size - 1);
        fs.closeSync(fd);
        if (b[0] !== 0x0a) lead = '\n';
      }
    } catch {}
    fs.appendFileSync(file, lead + JSON.stringify(rec) + '\n');
  } catch (e) {
    if (claimed) fs.rmSync(claimed, { force: true }); // 저장하지 못했으면 표식을 풀어 다음 포착이 남기게 한다
    throw e;
  }
  return rec;
}
// 입력함에 그 ID의 기록이 있는지(문자열 검색, 중복 판정 전용).
function inboxHas(P, id) {
  // 깨진 줄 안의 ID 문자열은 기록이 아니다. 온전히 읽히는 기록만 센다.
  return listInboxAll(P).some((r) => r.id === id);
}

// 선택지(AskUserQuestion) 응답 포착. Claude PostToolUse 훅 입력의 tool_response.answers → tool_input.answers 순으로 읽는다.
// 사람이 고른 것인지 증명할 수 없으므로(훅의 updatedInput·자동 응답이 답을 넣을 수 있다) 출처는 unknown이고 승인 근거가 아니다.
// 미분류 게이트와 지시형 판정에는 들어간다. 형식을 못 읽어도 원시 입력 전체를 보존한다.
export function captureChoice(P, { tool, payload }) {
  let obj = {};
  try {
    obj = JSON.parse(payload || '{}');
  } catch {
    obj = { raw: String(payload) };
  }
  if (!obj || typeof obj !== 'object' || Array.isArray(obj)) obj = { raw: String(payload) };
  const ts = new Date().toISOString();
  const session = obj.session_id ?? obj.sessionId ?? null;
  const useId = obj.tool_use_id ?? obj.toolUseId ?? null;
  const input = obj.tool_input ?? {};
  const resp = obj.tool_response ?? {};
  const answers = (resp && typeof resp === 'object' && resp.answers) || input.answers || null;
  const questions = Array.isArray(resp?.questions) ? resp.questions : Array.isArray(input.questions) ? input.questions : [];
  const base = { ts, tool, session, cwd: obj.cwd ?? P.top, origin: 'unknown', kind: 'choice', tool_use_id: useId };
  const raw = JSON.stringify({ tool_input: obj.tool_input ?? null, tool_response: obj.tool_response ?? null, ...(obj.raw ? { raw: obj.raw } : {}) }); // 원시 응답은 항상 보존한다
  if (!answers || typeof answers !== 'object' || !Object.keys(answers).length) {
    process.stderr.write('WARN 선택지 응답 형식을 읽지 못해 원시 응답만 입력함에 남겼다(plan triage --list로 확인).\n');
    return [persistRecord(P, { ...base, id: sha256(ts + raw).slice(0, 12), prompt: `[선택지 응답 형식을 읽지 못함] ${raw}`, raw, origin_note: '선택지 응답 형식 불명' }, session && useId ? `${tool}:${session}:${useId}:raw` : null)].filter(Boolean);
  }
  const out = [];
  Object.entries(answers).forEach(([question, answer], qi) => {
    const q = questions.find((x) => x?.question === question) ?? {};
    const labels = (q.options ?? []).map((o) => String(o?.label ?? o)).filter(Boolean);
    const text = typeof answer === 'string' ? answer : JSON.stringify(answer); // 문자열이 아닌 응답도 원문을 잃지 않게
    const parts = typeof answer === 'string' ? answer.split(',').map((x) => x.trim()).filter(Boolean) : [];
    const choice_label = parts.length > 0 && parts.every((x) => labels.includes(x));
    const rec = { ...base, id: sha256(ts + question + text).slice(0, 12), prompt: text, question, options: labels, choice_label, annotations: resp?.annotations ?? null, raw };
    const r = persistRecord(P, rec, session && useId ? `${tool}:${session}:${useId}:${qi}` : null);
    if (r) out.push(r);
  });
  return out;
}

// Codex rollout 첫 줄(session_meta)로 세션 종류를 판정한다. 첫 줄이 길 수 있어(기본 지침 포함) 줄바꿈까지 나눠 읽는다.
export function codexSessionKind(file) {
  let fd;
  try {
    fd = fs.openSync(file, 'r');
    const chunks = [];
    const buf = Buffer.alloc(1 << 20);
    for (let pos = 0, total = 0; total < 8 << 20; ) {
      const n = fs.readSync(fd, buf, 0, buf.length, pos);
      if (!n) break;
      const nl = buf.subarray(0, n).indexOf(0x0a);
      chunks.push(Buffer.from(buf.subarray(0, nl < 0 ? n : nl)));
      if (nl >= 0) break;
      pos += n;
      total += n;
    }
    const first = JSON.parse(Buffer.concat(chunks).toString('utf8'));
    const meta = first?.payload ?? first ?? {};
    if (first?.type !== 'session_meta' && !meta.originator) return 'unknown';
    return meta.originator === 'codex_exec' || meta.source === 'exec' ? 'exec' : 'interactive';
  } catch {
    return 'unreadable';
  } finally {
    if (fd !== undefined) fs.closeSync(fd);
  }
}
